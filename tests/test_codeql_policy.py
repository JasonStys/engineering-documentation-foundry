def test_actual_codeql_workflow(repository_root: Path) -> None:
    """Check the real workflow independently of successful application unit tests."""

    workflow = repository_root / ".github/workflows/codeql.yml"
    _assert_policy(yaml.safe_load(workflow.read_text(encoding="utf-8")))


@pytest.mark.parametrize(("name", "original", "replacement"), MUTATIONS)
def test_unsafe_codeql_mutations(
    repository_root: Path, name: str, original: str, replacement: str
) -> None:
    """Prove unsafe or incomplete configurations cannot satisfy the policy."""

    source = (repository_root / ".github/workflows/codeql.yml").read_text(encoding="utf-8")
    assert original in source, name
    with pytest.raises((AssertionError, KeyError, TypeError, ValueError, yaml.YAMLError)):
        _assert_policy(yaml.safe_load(source.replace(original, replacement, 1)))
