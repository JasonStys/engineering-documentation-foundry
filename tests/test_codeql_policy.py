MATRIX_EXPRESSION = "${{ matrix.language }}"


def _assert_policy(workflow: dict[str, Any]) -> None:
    """Enforce triggers, full analysis, immutable actions and scoped upload authority."""

    assert set(workflow) == {"name", True, "permissions", "concurrency", "jobs"}
    assert workflow["name"] == "CodeQL"
    # PyYAML's safe loader follows YAML 1.1 and reads the unquoted on key as True.
    assert workflow[True] == {
        "push": {"branches": ["main"]},
        "pull_request": {"branches": ["main"]},
        "schedule": [{"cron": "41 7 * * 2"}],
        "workflow_dispatch": None,
    }
    assert workflow["permissions"] == {"contents": "read"}
    assert set(workflow["jobs"]) == {"analyze"}
    job = workflow["jobs"]["analyze"]
    assert set(job) == {"name", "runs-on", "timeout-minutes", "permissions", "strategy", "steps"}
    assert job["runs-on"] == "ubuntu-24.04"
    assert job["timeout-minutes"] == 20
    assert job["permissions"] == {"contents": "read", "security-events": "write"}
    assert job["strategy"] == {
        "fail-fast": False,
        "matrix": {"language": ["python", "javascript-typescript", "actions"]},
    }
    steps = job["steps"]
    assert len(steps) == 3
    checkout, init, analyze = steps
    for step in steps:
        assert set(step) == {"name", "uses", "with"}
        assert re.fullmatch(r"[\w-]+/[\w-]+(?:/[\w-]+)?@[0-9a-f]{40}", step["uses"])
    assert checkout["uses"].startswith("actions/checkout@")
    assert checkout["with"] == {"persist-credentials": False}
    assert init["uses"].startswith("github/codeql-action/init@")
    assert analyze["uses"].startswith("github/codeql-action/analyze@")
    assert init["uses"].split("@")[1] == analyze["uses"].split("@")[1]
    assert init["with"] == {
        "languages": MATRIX_EXPRESSION,
        "build-mode": "none",
        "queries": "security-extended",
        "dependency-caching": False,
        "trap-caching": False,
    }
    assert analyze["with"] == {
        "category": "/language:" + MATRIX_EXPRESSION,
        "upload-database": False,
        "wait-for-processing": True,
    }


