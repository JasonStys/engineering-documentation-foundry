@pytest.mark.parametrize("blocked", [False, True])
def test_actual_direct_original_worker_has_cited_complete_outputs(
    tmp_path: Path, repository_root: Path, blocked: bool
) -> None:
    """The same production entry writes a real site or blocked corpus, with exact request and
    artifact binding.
    """
    source = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    project = ProjectInput.model_validate(
        authored(source, checksum="0" * 64 if blocked else digest)
    )
    request = canonical(
        {
            "project": project.model_dump(mode="json"),
            "files": {digest: base64.b64encode(source).decode()},
        }
    )
    output = io.BytesIO()
    original_stdin = sys.stdin
    try:
        sys.stdin = SimpleNamespace(buffer=io.BytesIO(request))
        assert worker.main(tmp_path, output) == 0
    finally:
        sys.stdin = original_stdin
    response = json.loads(output.getvalue())
    report, archive = pack(tmp_path / "publication")
    assert response["publication_allowed"] is (not blocked)
    assert response["build_id"] == report["build_id"]
    assert (
        response["project_sha256"]
        == hashlib.sha256(canonical(project.model_dump(mode="json"))).hexdigest()
    )
    files = unpack(archive)
    assert ("site/index.html" in files) is (not blocked)
    assert ("PUBLICATION_BLOCKED.txt" in files) is blocked
    topics = json.loads(files["canonical/topics.json"])
    if blocked:
        assert topics == [] and report["issue_counts"]["error"] > 0
    else:
        assert {block["provenance"]["page"] for topic in topics for block in topic["blocks"]} == {
            1,
            2,
        }


@pytest.mark.parametrize("fault", ["occupied", "inventory", "identity", "invalid-json"])
def test_actual_worker_refuses_invalid_job_without_publication(
    tmp_path: Path, repository_root: Path, fault: str, capsys: Any
) -> None:
    """Malformed snapshots cannot become a successful protocol packet or a publication claim."""
    source = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if fault == "occupied":
        (tmp_path / "prior-evidence.txt").write_text("preserve", encoding="utf-8")
    project = authored(source)
    files = (
        {}
        if fault == "inventory"
        else {
            digest: base64.b64encode(
                source + b"changed" if fault == "identity" else source
            ).decode()
        }
    )
    request = (
        b"not JSON" if fault == "invalid-json" else canonical({"project": project, "files": files})
    )
    original_stdin = sys.stdin
    output = io.BytesIO()
    try:
        sys.stdin = SimpleNamespace(buffer=io.BytesIO(request))
        assert worker.main(tmp_path, output) == 1
    finally:
        sys.stdin = original_stdin
    assert not output.getvalue() and not (tmp_path / "publication").exists()
    assert "job failed" in capsys.readouterr().err


@pytest.mark.parametrize("fault", ["timeout", "stdout", "stderr", "exit", "malformed"])
def test_real_owned_child_limits_reap_exact_child_and_do_not_save_evidence(
    tmp_path: Path, repository_root: Path, fault: str
) -> None:
    """Actual inert Python subprocesses hit deadline, stream and protocol guards; no timer
    fabricates success.
    """
    statements = {
        "timeout": "import time; time.sleep(30)",
        "stdout": "import sys; sys.stdout.buffer.write(b'x'*70000);sys.stdout.flush()",
        "stderr": "import sys; sys.stderr.buffer.write(b'x'*70000);sys.stderr.flush()",
        "exit": "import sys;sys.stderr.write('controlled failure');sys.exit(7)",
        "malformed": "print('not a JSON outcome')",
    }
    source = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    engine = Engine(
        [sys.executable, "-I", "-c", statements[fault]],
        {},
        dict(os.environ),
        timeout=0.25 if fault == "timeout" else 3,
    )
    with pytest.raises(ValueError):
        engine.run(ProjectInput.model_validate(authored(source)), {digest: source})
    assert list(tmp_path.iterdir()) == []


