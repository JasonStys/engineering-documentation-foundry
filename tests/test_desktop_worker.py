def test_actual_child_reader_failure_after_valid_bytes_is_not_silently_accepted(
    tmp_path, monkeypatch
):
    """Reject a failed actual pipe read even after a successful child emitted valid bytes."""
    actual = engine_module.subprocess.Popen

    class FaultingRead:
        """Inject one OS read error after the genuine child pipe returned its actual bytes."""

        def __init__(self, stream):
            """Bind the opened real stream without altering its underlying descriptor identity."""
            self.stream, self.reads = stream, 0

        def read(self, size):
            """Read actual process output once; expose a controlled later descriptor failure."""
            self.reads += 1
            if self.reads > 1:
                raise OSError("controlled post-payload pipe read failure")
            return self.stream.read(size)

        def close(self):
            """Close the actual child descriptor on every failure path."""
            self.stream.close()

    def child(*args, **kwargs):
        """Start the real inert child, replacing only its read adapter for this failure oracle."""
        process = actual(*args, **kwargs)
        process.stdout = FaultingRead(process.stdout)
        return process

    monkeypatch.setattr(engine_module.subprocess, "Popen", child)
    engine = Engine(
        [
            sys.executable,
            "-I",
            "-c",
            "import sys;sys.stdin.buffer.read();print('{\"valid\":true}')",
        ],
        {},
        dict(os.environ),
        timeout=3,
    )
    with pytest.raises(ValueError, match="processing failed"):
        engine._invoke(tmp_path, b"inert fixed input")


@pytest.mark.parametrize(
    "mutation",
    [
        "manifest",
        "manifest-type",
        "row",
        "duplicate",
        "missing-report",
        "published",
        "blocked",
        "decision",
    ],
)
def test_manifest_and_decision_negatives_use_actual_original_engine_artifacts(
    tmp_path: Path, repository_root: Path, mutation: str
) -> None:
    """Recomputed outer checksums cannot bless inconsistent original output inventories or
    publication states.
    """
    raw = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    worker.execute(
        tmp_path,
        canonical({"project": authored(raw), "files": {digest: base64.b64encode(raw).decode()}}),
    )
    _, archive = pack(tmp_path / "publication")
    files = unpack(archive)
    manifest = json.loads(files["build-manifest.json"])
    if mutation == "manifest":
        files.pop("build-manifest.json")
    elif mutation == "manifest-type":
        files["build-manifest.json"] = b"[]"
    elif mutation == "row":
        manifest["files"][0]["unexpected"] = True
    elif mutation == "duplicate":
        manifest["files"].append(manifest["files"][0])
    else:
        if mutation == "missing-report":
            files.pop("reports/migration-report.json")
        elif mutation == "published":
            files.pop("site/index.html")
        elif mutation == "blocked":
            report = json.loads(files["reports/migration-report.json"])
            report["publication_allowed"] = False
            files["reports/migration-report.json"] = canonical(report)
            files["PUBLICATION_BLOCKED.txt"] = b"blocked"
        elif mutation == "decision":
            report = json.loads(files["reports/migration-report.json"])
            report["publication_allowed"] = None
            files["reports/migration-report.json"] = canonical(report)
        manifest["files"] = [
            {"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
            for name, data in files.items()
            if name != "build-manifest.json"
        ]
    if "build-manifest.json" in files and mutation != "manifest-type":
        files["build-manifest.json"] = canonical(manifest)
    with pytest.raises((ValueError, KeyError)):
        checked_files(files)
