from __future__ import annotations

import json
from pathlib import Path

import pytest

from foundry_desktop.setup_window import TERMS, description
from tools.smoke_app import setup_display


@pytest.mark.parametrize("fault", [None, "host", "suffix", "size", "missing", "exit"])
def test_exact_setup_disclosure_is_distinct_from_provider_or_byte_authorization(
    repository_root: Path, fault: str | None
) -> None:
    """A real-looking domain in a different URL or absent consent field cannot pass the receipt."""
    pin = json.loads(
        (repository_root / "src/foundry_desktop/resources/pymupdf-wheels.json").read_text()
    )["wheels"]["win32-amd64"]
    output = TERMS + "\n\n" + description(pin) + "\nType INSTALL: "
    if fault == "host":
        output = output.replace("https://files.pythonhosted.org/", "https://evil.example/")
    elif fault == "suffix":
        output = output.replace(pin["url"], pin["url"] + ".unexpected")
    elif fault == "size":
        output = output.replace(f"Bytes: {pin['bytes']:,}", "Bytes: 1")
    elif fault == "missing":
        output = output.replace(f"ABI: {pin['tag']}\n", "")
    if fault is None:
        setup_display(0, output, pin)
    else:
        with pytest.raises(ValueError, match="exact disclosure"):
            setup_display(1 if fault == "exit" else 0, output, pin)
