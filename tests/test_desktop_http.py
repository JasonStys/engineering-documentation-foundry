def test_closed_real_http_inputs_preserve_the_empty_workspace(
    owned: tuple[Host, httpx.Client],
    method: str,
    path: str,
    body: bytes | None,
    expected: int,
) -> None:
    """Ambiguous JSON, unsafe framing/actions and malformed uploads return meaningful
    non-success statuses.
    """
    host, client = owned
    response = client.request(
        method, path, content=body, headers={"Content-Type": "application/json"} if body else {}
    )
    assert response.status_code == expected, response.text
    assert "access-control-allow-origin" not in response.headers
    assert host.service.store.library() == [] and host.service.store.listing("projects") == []


def test_action_query_is_refused_before_any_declared_body_is_sent(owned) -> None:
    """Require actual400 before body upload without racing Windows unread-body closure."""
    host, _ = owned
    with socket.create_connection(("127.0.0.1", host.server.server_port), timeout=3) as stream:
        stream.sendall(
            (
                "POST /api/save?other=x HTTP/1.1\r\n"
                + f"Host: {host.authority}\r\nOrigin: {host.url}\r\n"
                + f"X-Foundry-Capability: {host.token}\r\n"
                + "Content-Type: application/json\r\nContent-Length: 2\r\n"
                "Expect: 100-continue\r\n\r\n"
            ).encode()
        )
        header = bytearray()
        while not header.endswith(b"\r\n\r\n"):
            chunk = stream.recv(1)
            assert chunk and len(header) < 4096
            header.extend(chunk)
        assert bytes(header).startswith(b"HTTP/1.1 400 ")
        assert b"100 Continue" not in header
    assert host.service.store.library() == [] and host.service.store.listing("projects") == []


def test_actual_admitted_body_drain_keeps_lock_until_real_request_finishes(
    tmp_path: Path,
) -> None:
    """A real100-continue held transport stays owned through repeated Quit and releases only
    after completion.
    """
    directory = tmp_path / "owned"
    host = Host(directory, load())
    host.ready()
    stream = socket.create_connection(("127.0.0.1", host.server.server_port), timeout=3)
    drain = threading.Thread(target=host.drain)
    try:
        body = canonical({"name": "calibration"})
        stream.sendall(
            (
                "POST /api/example HTTP/1.1\r\n"
                f"Host: {host.authority}\r\nOrigin: {host.url}\r\n"
                f"X-Foundry-Capability: {host.token}\r\n"
                "Content-Type: application/json\r\n"
                f"Content-Length: {len(body)}\r\nExpect: 100-continue\r\n\r\n"
            ).encode()
        )
        assert stream.recv(4096) == b"HTTP/1.1 100 Continue\r\n\r\n"
        host.request_close()
        host.request_close()
        drain.start()
        assert not host.stopped.is_set()
        with pytest.raises((ValueError, OSError)):
            unexpected = Profile(directory)
            try:
                pytest.fail("The closing owner's actual workspace lock was released early")
            finally:
                unexpected.close()
        stream.sendall(body)
        response = http.client.HTTPResponse(stream)
        response.begin()
        value = json.loads(response.read())
        assert response.status == 201 and value["revision"] == 1
        drain.join(8)
        assert not drain.is_alive() and host.stopped.is_set()
        reopened = Profile(directory)
        try:
            assert reopened.store.project(value["id"])["input"] == value["input"]
        finally:
            reopened.close()
        with pytest.raises(OSError):
            socket.create_connection(("127.0.0.1", host.server.server_port), timeout=1)
    finally:
        stream.close()
        if drain.is_alive():
            drain.join(8)
        host.drain()


def test_actual_quit_readiness_csp_and_unicode_credential_contract(
    owned: tuple[Host, httpx.Client],
) -> None:
    """Quit requests closure without falsely claiming drain; app resources contain no remote
    authority.
    """
    host, client = owned
    assert equal("é", host.token) is False and equal(None, host.token) is False
    ready = host.ready()
    assert ready["nonce"] == host.nonce
    page = client.get("/")
    assert page.status_code == 200 and b"Jason Stys" in page.content
    assert "default-src 'none'" in page.headers["content-security-policy"]
    assert client.get("/assets/app.js").status_code == 200
    assert client.post("/api/quit", json={"confirm": True}).json() == {
        "close_requested": True,
        "owned_work_must_finish": True,
    }
    assert host.closing.is_set() and not host.stopped.is_set()
    connection = http.client.HTTPConnection("127.0.0.1", host.server.server_port, timeout=3)
    try:
        connection.putrequest("POST", "/api/example")
        for key, value in {
            "Origin": host.url,
            "X-Foundry-Capability": host.token,
            "Content-Type": "application/json",
            "Content-Length": "14",
            "Expect": "100-continue",
        }.items():
            connection.putheader(key, value)
        connection.endheaders()
        assert connection.getresponse().status == 409
    finally:
        connection.close()
