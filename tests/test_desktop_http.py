@pytest.fixture
def owned(tmp_path: Path) -> Iterator[tuple[Host, httpx.Client]]:
    """Start an actual fresh ephemeral listener and join it before releasing its workspace."""
    host = Host(tmp_path / "workspace", load())
    host.ready()
    try:
        with httpx.Client(
            base_url=host.url,
            timeout=70,
            trust_env=False,
            headers={"Origin": host.url, "X-Foundry-Capability": host.token},
        ) as client:
            yield host, client
    finally:
        host.drain()


def test_actual_authoring_revision_build_compare_preview_and_exact_roundtrip(
    owned: tuple[Host, httpx.Client],
    repository_root: Path,
) -> None:
    """A user authors real uploaded bytes, inspects original findings and exports exact
    durable evidence.
    """
    host, client = owned
    original = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    digest = hashlib.sha256(original).hexdigest()
    upload = client.post(
        "/api/upload",
        json={
            "name": "Service calibration.pdf",
            "base64": base64.b64encode(original).decode(),
        },
    )
    assert upload.status_code == 201 and upload.json()["sha256"] == digest
    assert (
        client.post(
            "/api/upload",
            json={
                "name": "Other display name.pdf",
                "base64": base64.b64encode(original).decode(),
            },
        ).status_code
        == 200
    )
    downloaded = client.get("/api/source", params={"sha256": digest})
    assert downloaded.content == original and downloaded.headers["content-type"] == (
        "application/pdf"
    )
    assert client.get("/api/source", params={"sha256": "0" * 64}).status_code == 404
    assert client.get("/api/source", params={"sha256": "../outside"}).status_code == 400
    draft = {
        "title": "Calibration%_ <script>inert</script>",
        "registry": {
            "registry_version": 1,
            "sources": [],
        },
        "limits": {},
    }
    appended = client.post(
        "/api/append-source",
        json={
            "input": json.dumps(draft),
            "sha256": digest,
            "pin_checksum": True,
            "metadata": {
                "source_id": "authored-calibration",
                "revision": "A",
                "product_model": "Synthetic instrument",
                "owner": "Service documentation",
                "license": "MIT original synthetic fixture",
                "migration_status": "in-review",
            },
        },
    )
    assert appended.status_code == 200 and appended.json()["saved"] is False
    draft = appended.json()["input"]
    validation = client.post("/api/validate", json={"input": json.dumps(draft)})
    assert validation.status_code == 200
    assert {
        key: validation.json()[key]
        for key in ("source_count", "unique_pdfs", "bytes", "pdfs_processed")
    } == {
        "source_count": 1,
        "unique_pdfs": 1,
        "bytes": len(original),
        "pdfs_processed": False,
    }
    saved = client.post("/api/save", json={"id": None, "revision": 0, "input": json.dumps(draft)})
    assert saved.status_code == 201 and saved.json()["revision"] == 1
    project = saved.json()
    assert client.post("/api/delete-source", json={"sha256": digest}).status_code == 409
    stale = client.post("/api/save", json={"id": project["id"], "revision": 0, "input": draft})
    assert stale.status_code == 409
    built = client.post("/api/build", json={"id": project["id"], "revision": 1})
    assert built.status_code == 201, built.text
    record = built.json()
    assert record["status"] == "published" and record["report"]["publication_allowed"] is True
    detail = client.get("/api/detail", params={"id": record["id"], "q": "vent the port"}).json()
    assert len(detail["topics"]) == 1 and detail["topic_total"] >= 2
    assert any(
        block["warning"]["avoidance"] == "vent the port"
        for topic in detail["topics"]
        for block in topic["blocks"]
        if block["warning"]
    )
    assert (
        client.get("/api/detail", params={"id": record["id"], "kind": "invalid"}).status_code == 400
    )
    assert (
        client.get("/api/detail", params={"id": record["id"], "source": "absent"}).json()["topics"]
        == []
    )
    bundle = client.get("/api/export-build", params={"id": record["id"], "kind": "zip"})
    files = unpack(bundle.content)
    assert hashlib.sha256(bundle.content).hexdigest() == record["sha"]
    artifact = client.get(
        "/api/artifact", params={"id": record["id"], "path": "canonical/topics.json"}
    )
    assert artifact.content == files["canonical/topics.json"]
    preview = "/preview/" + record["id"] + "/site/index.html"
    assert client.get(preview).status_code == 403
    grant = client.post("/api/preview-session", json={"purpose": "preview"})
    assert grant.status_code == 200 and "HttpOnly" in grant.headers["set-cookie"]
    rendered = client.get(preview)
    assert rendered.content == files["site/index.html"]
    assert "sandbox allow-same-origin" in rendered.headers["content-security-policy"]
    assert "script-src" not in rendered.headers["content-security-policy"]
    with httpx.Client(base_url=host.url, trust_env=False, cookies=client.cookies) as cookie_only:
        assert cookie_only.get("/api/projects").status_code == 403
    evidence = client.get("/api/export-build", params={"id": record["id"], "kind": "evidence"})
    assert evidence.json() == record
    exported = client.get("/api/export-project", params={"id": project["id"], "revision": 1})
    assert base64.b64decode(exported.json()["files"][0]["base64"]) == original
    copied = client.post("/api/import", json=exported.text)
    assert copied.status_code == 201 and copied.json()["id"] != project["id"]
    changed = {**draft, "title": "Calibration revision B"}
    changed["registry"] = {
        **draft["registry"],
        "sources": [{**draft["registry"]["sources"][0], "revision": "B"}],
    }
    revised = client.post("/api/save", json={"id": project["id"], "revision": 1, "input": changed})
    assert revised.status_code == 201 and revised.json()["revision"] == 2
    newer = client.post("/api/build", json={"id": project["id"], "revision": 2}).json()
    compared = client.post("/api/compare", json={"before": record["id"], "after": newer["id"]})
    assert compared.status_code == 200, compared.text
    review = compared.json()
    assert review["saved"] is False and json.loads(review["json"]) == review["report"]
    assert review["before_build"] == record["id"] and review["after_build"] == newer["id"]
    assert review["report"]["counts"]["changed"] > 0
    assert (
        "Corpus revision review" in review["html"]
        and ("Source authored-calibration") in review["html"]
    )
    assert len(client.get("/api/builds", params={"status": "published"}).json()) == 2
    assert len(client.get("/api/projects", params={"q": "%_"}).json()) == 1
    assert client.get("/api/projects", params={"q": "no such title"}).json() == []
    assert (
        client.post("/api/delete-project", json={"id": project["id"], "revision": 1}).status_code
        == 409
    )
    assert client.post("/api/delete-build", json={"id": record["id"]}).status_code == 200
    assert client.get("/api/detail", params={"id": record["id"]}).status_code == 404
    assert len(client.get("/api/builds").json()) == 1


@pytest.mark.parametrize(
    "path",
    ["/api/library", "/api/projects", "/api/builds", "/api/detail?id=" + "a" * 32],
)
def test_api_has_no_anonymous_or_cookie_authority(
    owned: tuple[Host, httpx.Client], path: str
) -> None:
    """An exact local origin alone does not expose private source/project/build information."""
    host, _ = owned
    with httpx.Client(base_url=host.url, trust_env=False) as anonymous:
        assert anonymous.get(path).status_code == 403
        assert anonymous.get(path, headers={"X-Foundry-Capability": "wrong"}).status_code == 403
        assert (
            anonymous.get(
                path,
                headers={
                    "X-Foundry-Capability": host.token,
                    "Origin": "https://outside.invalid",
                },
            ).status_code
            == 403
        )


@pytest.mark.parametrize(
    "headers,expected",
    [
        ({"Host": "localhost:99"}, 403),
        ({"Origin": "https://outside.invalid"}, 403),
        ({"X-Foundry-Capability": "wrong"}, 403),
        ({"Content-Type": "text/plain"}, 400),
        ({"Content-Length": str(MAX_REQUEST + 1)}, 400),
        ({"Transfer-Encoding": "chunked"}, 400),
        ({"Expect": "unexpected"}, 400),
    ],
)
def test_real_headers_only_refusals_do_not_wait_for_untrusted_body(
    owned: tuple[Host, httpx.Client],
    headers: dict[str, str],
    expected: int,
) -> None:
    """Send an actual declared body without bytes; auth/framing refuses before granting100 or
    reading it.
    """
    host, _ = owned
    fields = {
        "Host": host.authority,
        "Origin": host.url,
        "X-Foundry-Capability": host.token,
        "Content-Type": "application/json",
        "Content-Length": "17",
        **headers,
    }
    with socket.create_connection(("127.0.0.1", host.server.server_port), timeout=3) as stream:
        stream.sendall(
            (
                "POST /api/quit HTTP/1.1\r\n"
                + "".join(f"{key}: {value}\r\n" for key, value in fields.items())
                + "\r\n"
            ).encode("ascii")
        )
        received = stream.recv(4096)
        assert received.startswith(f"HTTP/1.1 {expected} ".encode())
    assert not host.closing.is_set()


