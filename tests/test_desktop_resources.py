@pytest.mark.parametrize(
    "fault",
    [
        None,
        "source",
        "product",
        "version",
        "dirty",
        "assets",
        "asset-bytes",
        "parser-pins",
        "example-bytes",
    ],
)
def test_native_resources_bind_actual_closed_assets_examples_and_metadata(
    tmp_path: Path, repository_root: Path, monkeypatch: Any, fault: str | None
) -> None:
    """Matching outer labels alone cannot authorize substituted UI, prepared bytes or parser
    URLs.
    """
    identity = native_fixture(tmp_path, repository_root, monkeypatch)
    if fault in {"source", "product", "version", "dirty", "assets"}:
        identity[{"source": "sourceCommit", "dirty": "sourceDirty"}.get(fault, fault)] = {
            "source": "short",
            "product": "other",
            "version": "0.1.0",
            "dirty": "false",
            "assets": {},
        }[fault]
        (tmp_path / "RELEASE.json").write_bytes(canonical(identity))
    elif fault == "asset-bytes":
        (tmp_path / "web/assets/app.js").write_bytes(b"changed")
    elif fault == "parser-pins":
        (tmp_path / "foundry_desktop/resources/pymupdf-wheels.json").write_bytes(b"changed")
    elif fault == "example-bytes":
        (tmp_path / "examples/sensor-calibration.pdf").write_bytes(b"changed")
    if fault is not None:
        with pytest.raises(ValueError):
            load()
    else:
        actual = load()
        assert actual.identity == identity and set(actual.assets) == {
            "/",
            *("/" + name for name in ASSETS),
        }
        assert actual.command == (sys.executable, "--engine-job")


@pytest.mark.parametrize("system", ["win32", "darwin", "linux"])
def test_os_data_and_dependency_locations_are_separate_from_installation(
    tmp_path: Path, monkeypatch: Any, system: str
) -> None:
    """The normal menu chooses user-data paths without opening/creating a profile or
    dependency store.
    """
    monkeypatch.setattr(sys, "platform", system)
    monkeypatch.setenv("LOCALAPPDATA", str(tmp_path))
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path))
    monkeypatch.setattr(Path, "home", lambda: tmp_path)
    monkeypatch.delenv("FOUNDRY_DEPENDENCY_HOME", raising=False)
    data = profile.default_directory()
    dependency = parser_setup.dependency_home()
    assert data != dependency and data.name == "profile" and dependency.name == "dependencies"
    assert not data.exists() and not dependency.exists()


def test_unknown_workspace_schema_and_wrong_marker_preserve_previous_files(tmp_path: Path) -> None:
    """A future database or foreign marker is refused without a destructive reset/migration."""
    path = tmp_path / "future"
    workspace = Profile(path)
    with workspace.store.connect() as database:
        database.execute("PRAGMA user_version=2")
    workspace.close()
    with pytest.raises(ValueError, match="future"):
        Profile(path)
    assert (path / "workspace.sqlite3").is_file()
    other = tmp_path / "other"
    other.mkdir()
    (other / "profile.json").write_bytes(b'{"product":"another","schema_version":1}')
    before = (other / "profile.json").read_bytes()
    with pytest.raises(ValueError, match="identity"):
        Profile(other)
    assert (other / "profile.json").read_bytes() == before


def test_upload_capacity_and_missing_source_never_evict_previous_bytes(
    tmp_path: Path, repository_root: Path, monkeypatch: Any
) -> None:
    """Explicit quota failures, corrupt retained bytes and missing references leave prior
    library data intact.
    """
    original = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    workspace = Profile(tmp_path / "workspace")
    try:
        uploaded = workspace.store.upload("service.pdf", original)
        project = ProjectInput.model_validate(authored(original))
        monkeypatch.setattr(store_module, "MAX_HISTORY", len(original))
        with pytest.raises(ValueError, match="256 MiB"):
            workspace.store.upload("new.pdf", original + b"new")
        assert workspace.store.source(uploaded["sha256"]) == original
        with workspace.store.connect() as database:
            database.execute("UPDATE pdfs SET data=? WHERE sha=?", (b"corrupt", uploaded["sha256"]))
        with pytest.raises(ValueError, match="identity"):
            workspace.store.source(uploaded["sha256"])
        with pytest.raises(ValueError, match="integrity"):
            workspace.store.files(project)
        with pytest.raises(KeyError):
            workspace.store.remove_pdf("0" * 64)
    finally:
        workspace.close()
