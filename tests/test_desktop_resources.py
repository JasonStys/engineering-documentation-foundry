def native_fixture(root: Path, repository: Path, monkeypatch: Any) -> dict[str, Any]:
    """Bind real UI/example bytes to independent synthetic metadata without executing an
    invented binary.
    """
    web = root / "web"
    for name in ASSETS:
        path = web / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes((repository / "web/dist" / name).read_bytes())
    examples = root / "examples"
    examples.mkdir()
    for name in EXAMPLES:
        (examples / name).write_bytes((repository / "examples/sources" / name).read_bytes())
    pin = root / "foundry_desktop/resources/pymupdf-wheels.json"
    pin.parent.mkdir(parents=True)
    pin.write_bytes((repository / "src/foundry_desktop/resources/pymupdf-wheels.json").read_bytes())
    dll = root / "python314.dll"
    dll.write_bytes(b"inert resource identity fixture; never executed")
    identity = {
        "product": "engineering-documentation-foundry",
        "version": "0.2.0",
        "pythonVersion": platform.python_version(),
        "sourceCommit": "a" * 40,
        "sourceDirty": False,
        "parserPinsSha256": hashlib.sha256(pin.read_bytes()).hexdigest(),
        "pythonRuntimeSha256": hashlib.sha256(dll.read_bytes()).hexdigest(),
        "assets": {name: hashlib.sha256((web / name).read_bytes()).hexdigest() for name in ASSETS},
        "examples": {
            name: hashlib.sha256((examples / name).read_bytes()).hexdigest() for name in EXAMPLES
        },
    }
    (root / "RELEASE.json").write_bytes(canonical(identity))
    monkeypatch.setattr(sys, "frozen", True, raising=False)
    monkeypatch.setattr(sys, "_MEIPASS", str(root), raising=False)
    # This isolates metadata admission on the original three older source-CI versions.
