from __future__ import annotations

import ast
import re
import subprocess
from pathlib import Path

PINNED_ACTION = re.compile(r"uses:\s+[\w-]+/[\w-]+(?:/[\w-]+)*@[0-9a-f]{40}(?:\s|$)")
FORBIDDEN_REFERENCES = (
    "".join(("op", "to", " ", "2", "2")),
    "".join(("op", "to", "2", "2")),
)


def _text_files(root: Path) -> tuple[Path, ...]:
    """Scan tracked/proposed public text while respecting ignored private runtime outputs."""

    suffixes = {
        ".md",
        ".py",
        ".toml",
        ".yaml",
        ".yml",
        ".json",
        ".txt",
        ".css",
        ".html",
        ".ts",
        ".mjs",
    }
    output = subprocess.check_output(
        [
            "git",
            "-c",
            "safe.directory=" + root.as_posix(),
            "-C",
            str(root),
            "ls-files",
            "--cached",
            "--others",
            "--exclude-standard",
            "-z",
        ]
    )
    result = []
    for name in sorted(set(output.decode("utf-8").split("\0")) - {""}):
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts or ".git" in relative.parts:
            raise ValueError("Invalid deliverable path")
        path = root / relative
        if path.is_symlink() or not path.is_file():
            raise ValueError("Deliverables must be ordinary files")
        if path.suffix.lower() in suffixes:
            result.append(path)
    return tuple(result)


def test_repository_is_employer_neutral_and_documented(repository_root: Path) -> None:
    """Keep prohibited employer references out and require core documentation."""

    combined = "\n".join(
        path.read_text(encoding="utf-8", errors="ignore") for path in _text_files(repository_root)
    ).casefold()
    assert not any(reference in combined for reference in FORBIDDEN_REFERENCES)
    for relative in (
        "README.md",
        "CONTRIBUTING.md",
        "SECURITY.md",
        "docs/architecture.md",
        "docs/testing-and-validation.md",
        "docs/file-reference.md",
    ):
        assert (repository_root / relative).is_file(), relative


def test_python_files_have_indexed_headers_and_symbol_docstrings(repository_root: Path) -> None:
    """Require module headers, resolved indexes, and function/class documentation."""

    python_files = tuple(
        sorted(
            path
            for directory in ("src", "tests", "tools")
            for path in (repository_root / directory).rglob("*.py")
        )
    )
    for path in python_files:
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source)
        assert ast.get_docstring(tree), path
        assert "@@SYMBOL_INDEX_START" in source and "@@SYMBOL_INDEX_END" in source
        assert any(
            marker in source
            for marker in ("- function ", "- class ", "- variable ", "- no top-level symbols")
        )
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                assert ast.get_docstring(node), f"{path}:{node.lineno} {node.name}"


def test_workflows_are_pinned_and_least_privilege(repository_root: Path) -> None:
    """Require immutable action pins and read-only default permissions."""

    workflows = tuple((repository_root / ".github" / "workflows").glob("*.yml"))
    assert workflows
    for workflow in workflows:
        text = workflow.read_text(encoding="utf-8")
        assert "permissions:\n  contents: read" in text
        uses_lines = [
            line.strip() for line in text.splitlines() if line.strip().startswith("uses:")
        ]
        assert uses_lines
        assert all(PINNED_ACTION.search(line) for line in uses_lines)


def test_action_pin_policy_supports_real_subactions_without_mutable_refs() -> None:
    """Accept pinned nested actions while rejecting mutable or malformed references."""

    digest = "a" * 40
    assert PINNED_ACTION.search(f"uses: actions/checkout@{digest}")
    assert PINNED_ACTION.search(f"uses: github/codeql-action/init@{digest} # reviewed")
    assert not PINNED_ACTION.search("uses: github/codeql-action/init@v4")
    assert not PINNED_ACTION.search(f"uses: github/codeql-action/init@{digest}b")
    assert not PINNED_ACTION.search(f"uses: github//init@{digest}")


def test_public_scan_retains_new_sources_and_ignores_private_outputs(
    tmp_path: Path,
) -> None:
    """Keep proposed TypeScript visible and ignored runtime data private in a real Git fixture."""
    subprocess.run(["git", "init", "--quiet", "--initial-branch=main", str(tmp_path)], check=True)
    (tmp_path / ".gitignore").write_text(".runtime/\nnode_modules/\n", encoding="utf-8")
    (tmp_path / "tracked.md").write_text("Tracked public documentation", encoding="utf-8")
    (tmp_path / "proposed.ts").write_text("// Proposed public editor source", encoding="utf-8")
    (tmp_path / ".runtime").mkdir()
    (tmp_path / ".runtime/private.ts").write_text("Synthetic private fixture", encoding="utf-8")
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules/vendor.ts").write_text(
        "Installed dependency fixture", encoding="utf-8"
    )
    subprocess.run(
        [
            "git",
            "-c",
            "safe.directory=" + tmp_path.as_posix(),
            "-C",
            str(tmp_path),
            "add",
            "tracked.md",
        ],
        check=True,
    )
    assert [path.name for path in _text_files(tmp_path)] == ["proposed.ts", "tracked.md"]
