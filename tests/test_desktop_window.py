def spin(window: desktop.Window, condition: Any, *, timeout: float = 5) -> None:
    """Process actual Tk events until the observed state or a fixed failure deadline, never
    retry work.
    """
    deadline = time.monotonic() + timeout
    while not condition() and time.monotonic() < deadline:
        window.root.update()
    assert condition(), "The real native control did not reach its expected state"


def test_native_owner_controls_minimum_window_and_actual_browser_quit(
    tmp_path: Path, monkeypatch: Any
) -> None:
    """Ordinary GUI controls open one actual workspace and keep Exit visible at the minimum size."""
    directory = tmp_path / "workspace"
    window = desktop.Window(load(), directory, no_browser=True)
    calls: list[str] = []
    monkeypatch.setattr(desktop.webbrowser, "open", lambda url, **_kw: calls.append(url) or True)
    monkeypatch.setattr(desktop.messagebox, "showinfo", lambda *args, **_kw: calls.append(args[1]))
    monkeypatch.setattr(desktop.filedialog, "askdirectory", lambda **_kw: str(directory))
    try:
        window.root.geometry("650x420")
        window.root.update()
        assert "0.2.0" in window.root.title() and "Jason Stys" in window.root.title()
        assert not directory.exists() and window.host is None
        for control in (window.exit_button, window.open_button, window.choose_button):
            assert control.winfo_ismapped()
            assert control.winfo_rooty() - window.root.winfo_rooty() >= 0
            assert (
                control.winfo_rooty() - window.root.winfo_rooty() + control.winfo_height()
                <= window.root.winfo_height()
            )
        window.choose_button.invoke()
        window.open_button.invoke()
        host = window.host
        assert host is not None and host.ready()["url"] == host.url
        assert str(window.open_button["state"]) == "disabled" and calls == []
        window.open()
        assert window.host is host
        window.browser_button.invoke()
        assert calls == [host.url + "/#native=" + host.token]
        window.help()
        assert "plaintext" in calls[-1] and "original PDF pipeline" in calls[-1]
        host.request_close()
        window.watch()
        spin(window, lambda: window.closer is not None)
        spin(window, lambda: host.stopped.is_set())
        if window.closer is not None:
            window.closer.join(5)
        assert host.stopped.is_set()
    finally:
        if window.host is not None:
            window.host.drain()
        try:
            window.root.destroy()
        except desktop.tk.TclError:
            assert window.host is not None and window.host.stopped.is_set()


def test_repeated_exit_does_not_release_actual_held_request_or_lock(tmp_path: Path) -> None:
    """Closing a real owner window waits on an authenticated in-flight handler instead of a
    timer.
    """
    window = desktop.Window(load(), tmp_path / "workspace", no_browser=True)
    window.open()
    host = window.host
    assert host is not None
    stream = socket.create_connection(("127.0.0.1", host.server.server_port), timeout=3)
    try:
        body = b'{"name":"calibration"}'
        stream.sendall(
            (
                "POST /api/example HTTP/1.1\r\n"
                f"Host: {host.authority}\r\nOrigin: {host.url}\r\n"
                f"X-Foundry-Capability: {host.token}\r\n"
                "Content-Type: application/json\r\n"
                f"Content-Length: {len(body)}\r\nExpect: 100-continue\r\n\r\n"
            ).encode()
        )
        assert stream.recv(4096) == b"HTTP/1.1 100 Continue\r\n\r\n"
        window.quit()
        first = window.closer
        window.quit()
        window.root.update()
        assert window.closer is first and first is not None and first.is_alive()
        assert not host.stopped.is_set() and window.root.winfo_exists()
        stream.sendall(body)
        while stream.recv(65536):
            pass
        first.join(5)
        assert not first.is_alive() and host.stopped.is_set()
        window.poll()
    finally:
        stream.close()
        host.drain()
        try:
            window.root.destroy()
        except desktop.tk.TclError:
            assert host.stopped.is_set()


def test_native_startup_and_browser_failures_are_visible_without_adopting_listener(
    tmp_path: Path, monkeypatch: Any
) -> None:
    """An unknown directory is preserved; browser failure leaves the actual healthy owner
    available to exit.
    """
    directory = tmp_path / "unknown"
    directory.mkdir()
    (directory / "sentinel.txt").write_text("preserve", encoding="utf-8")
    window = desktop.Window(load(), directory)
    try:
        window.open()
        assert window.host is None and window.failed and "did not start" in window.status.get()
        assert sorted(path.name for path in directory.iterdir()) == ["sentinel.txt"]
        window.directory.set(str(tmp_path / "valid"))
        monkeypatch.setattr(desktop.webbrowser, "open", lambda *_args, **_kw: False)
        window.open()
        assert (
            window.host is not None and not window.failed and "did not open" in window.status.get()
        )

        def failed_browser(*_args: Any, **_kw: Any) -> bool:
            """Represent an ordinary OS browser opener failure without changing the actual
            service.
            """
            raise OSError("controlled browser unavailable")

        monkeypatch.setattr(desktop.webbrowser, "open", failed_browser)
        window.browser()
        assert "controlled browser unavailable" in window.status.get()
        window.host.request_close()
        window.browser()
        window.quit()
        assert window.closer is not None
        window.closer.join(5)
        window.poll()
    finally:
        if window.host is not None:
            window.host.drain()
        try:
            window.root.destroy()
        except desktop.tk.TclError:
            assert window.host is not None and window.host.stopped.is_set()


def test_cancelled_native_setup_precedes_any_workspace_creation(
    tmp_path: Path, monkeypatch: Any
) -> None:
    """A frozen-mode Cancel returns before Host or a profile opens; source setup is
    explicitly different.
    """
    resources = load()
    monkeypatch.setattr(desktop, "load", lambda: resources)
    monkeypatch.setattr(sys, "frozen", True, raising=False)
    monkeypatch.setattr(desktop, "ensure", lambda **_kw: False)
    directory = tmp_path / "never-opened"
    assert desktop.main(["--no-window", "--no-browser", "--profile", str(directory)]) == 0
    assert not directory.exists()
    monkeypatch.setattr(desktop, "ensure", lambda **_kw: True)
    assert desktop.main(["--setup-engine"]) == 0 and not directory.exists()
    monkeypatch.delattr(sys, "frozen")
    assert desktop.main(["--setup-engine"]) == 0 and not directory.exists()


def test_console_entry_uses_actual_listener_and_normal_close(
    tmp_path: Path, monkeypatch: Any, capsys: Any
) -> None:
    """The non-window consumer still owns an actual listener, health identity and normal drain."""
    original = Host.ready

    def ready_and_close(host: Host) -> dict[str, Any]:
        """Perform the real readiness exchange before immediately requesting this exact
        owner's close.
        """
        ready = original(host)
        host.request_close()
        return ready

    monkeypatch.setattr(Host, "ready", ready_and_close)
    assert (
        desktop.main(["--no-window", "--no-browser", "--profile", str(tmp_path / "workspace")]) == 0
    )
    output = capsys.readouterr().out
    assert '"event": "ready"' in output and '"event": "stopped"' in output
    assert '"normal": true' in output


def test_post_setup_dependency_location_reaches_the_actual_owned_service(tmp_path, monkeypatch):
    """Bind the consent-selected path after setup instead of its stale environment snapshot."""
    monkeypatch.delenv("FOUNDRY_DEPENDENCY_HOME", raising=False)
    snapshot = load()
    assert "FOUNDRY_DEPENDENCY_HOME" not in snapshot.environment
    dependency = tmp_path / "configured-data/dependencies"

    def approved_setup(**_kwargs):
        """Model completed consent; this unit oracle executes no dependency code or network."""
        monkeypatch.setenv("FOUNDRY_DEPENDENCY_HOME", str(dependency))
        return True

    original = Host.ready

    def ready_and_close(host):
        """Inspect the owned child environment after the actual readiness exchange."""
        assert host.resources.environment["FOUNDRY_DEPENDENCY_HOME"] == str(dependency)
        value = original(host)
        host.request_close()
        return value

    monkeypatch.setattr(desktop, "load", lambda: snapshot)
    monkeypatch.setattr(sys, "frozen", True, raising=False)
    monkeypatch.setattr(desktop, "ensure", approved_setup)
    monkeypatch.setattr(desktop.parser_setup, "selected_pin", lambda: {"sha256": "a" * 64})
    monkeypatch.setattr(Host, "ready", ready_and_close)
    assert (
        desktop.main(["--no-window", "--no-browser", "--profile", str(tmp_path / "workspace")]) == 0
    )
