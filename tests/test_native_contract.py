@pytest.mark.parametrize(
    "path,key",
    [
        ("pyproject.toml", "version"),
        ("web/package.json", "version"),
        ("web/package-lock.json", "version"),
        ("web/public/index.html", "visible"),
    ],
)
def test_native_version_and_visible_editor_must_agree(
    tmp_path: Path, repository_root: Path, path: str, key: str
) -> None:
    """A metadata/footer drift cannot be frozen into a release-labelled application."""
    for name in (
        "pyproject.toml",
        "web/package.json",
        "web/package-lock.json",
        "web/public/index.html",
    ):
        target = tmp_path / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((repository_root / name).read_bytes())
    assert configuration(tmp_path) == "0.2.0"
    changed = tmp_path / path
    if changed.suffix == ".json":
        document = json.loads(changed.read_text(encoding="utf-8"))
        document[key] = "0.1.0"
        changed.write_text(json.dumps(document), encoding="utf-8")
    else:
        changed.write_text(
            changed.read_text(encoding="utf-8").replace("0.2.0", "0.1.0"), encoding="utf-8"
        )
    with pytest.raises(ValueError, match="mismatch"):
        configuration(tmp_path)


