def assert_native_policy(value: dict[str, Any]) -> None:
    """Keep three actual GUI consumers, ordinary authority and nonpublishing CI scope."""
    assert value["permissions"] == {"contents": "read"}
    assert value[True] == {
        "push": {"branches": ["main"]},
        "pull_request": None,
        "workflow_dispatch": None,
    }
    assert set(value["jobs"]) == {"portable"}
    job = value["jobs"]["portable"]
    assert set(job) == {"name", "runs-on", "timeout-minutes", "strategy", "steps"}
    assert job["timeout-minutes"] == 25
    assert job["strategy"] == {
        "fail-fast": False,
        "matrix": {"os": ["ubuntu-24.04", "windows-latest", "macos-latest"]},
    }
    assert not any("continue-on-error" in step or "if" in step for step in job["steps"])
    assert not any("upload-artifact" in step.get("uses", "") for step in job["steps"])
    steps = {step["name"]: step for step in job["steps"] if "name" in step}
    assert steps["Check out exact source without persisted credentials"]["with"] == {
        "persist-credentials": False
    }
    assert steps["Select the patched native Python runtime"]["with"] == {
        "python-version": "3.14.10",
        "check-latest": True,
    }
    assert steps["Install exact source and packaging locks"]["run"].splitlines() == [
        "python -m pip install --require-hashes -r requirements-dev.lock "
        "-r requirements-package.lock",
        "python -m pip install --no-deps --no-build-isolation -e .",
    ]
    assert (
        steps["Install the exact locked browser"]["run"]
        == "npm --prefix web exec -- playwright install chromium"
    )
    assert (
        steps["Prove actual browser host requirements"]["run"]
        == "npm --prefix web run check:browser-host"
    )
    actual = steps["Build, safely extract and use the actual application"]
    assert actual["shell"] == "bash"
    assert actual["run"].splitlines() == [
        "set -euo pipefail",
        'if [ "$RUNNER_OS" = "Linux" ]; then',
        "  command -v xvfb-run",
        "  xvfb-run -a python -m tools.package_app --output-root .runtime/native-ci",
        "else",
        "  python -m tools.package_app --output-root .runtime/native-ci",
        "fi",
    ]


def test_actual_native_workflow_and_original_coverage_floor(repository_root: Path) -> None:
    """Keep real commands, the original Python matrix and both-package coverage required."""
    assert_native_policy(
        yaml.safe_load(
            (repository_root / ".github/workflows/desktop.yml").read_text(encoding="utf-8")
        )
    )
    source = yaml.safe_load(
        (repository_root / ".github/workflows/ci.yml").read_text(encoding="utf-8")
    )
    assert source["jobs"]["verify"]["strategy"]["matrix"]["python-version"] == [
        "3.11",
        "3.12",
        "3.13",
    ]
    coverage = next(
        step
        for step in source["jobs"]["verify"]["steps"]
        if step.get("name") == "Test with branch coverage"
    )
    assert (
        coverage["run"]
        == "xvfb-run -a pytest --cov --cov-branch --cov-report=term-missing --cov-report=xml"
    )
    import tomllib

    project = tomllib.loads((repository_root / "pyproject.toml").read_text(encoding="utf-8"))
    # The console entrypoint and python -m pytest must collect the same local
    # packaging contracts, independent of the interpreter's initial sys.path.
    assert project["tool"]["pytest"]["ini_options"]["pythonpath"] == ["."]
    assert project["tool"]["coverage"]["report"]["fail_under"] == 90
    assert project["tool"]["coverage"]["run"]["source"] == ["docfoundry", "foundry_desktop"]


@pytest.mark.parametrize(
    "old,new",
    [
        ("contents: read", "contents: write"),
        ("pull_request:", "pull_request_target:"),
        ("timeout-minutes: 25", "continue-on-error: true\n    timeout-minutes: 25"),
        ("[ubuntu-24.04, windows-latest, macos-latest]", "[windows-latest]"),
        ('python-version: "3.14.10"', 'python-version: "3.14.6"'),
        ("--require-hashes", "--no-deps"),
        ("python -m tools.package_app", "python -m tools.fake_acceptance"),
        ("run: npm --prefix web run check:browser-host", "run: echo skipped-host-validation"),
    ],
)
def test_native_policy_rejects_real_unsafe_workflow_mutations(
    repository_root: Path, old: str, new: str
) -> None:
    """Reject source, runtime, platform, host and authority omissions in the actual workflow."""
    text = (repository_root / ".github/workflows/desktop.yml").read_text(encoding="utf-8")
    assert old in text
    with pytest.raises((AssertionError, KeyError, ValueError)):
        assert_native_policy(yaml.safe_load(text.replace(old, new)))
