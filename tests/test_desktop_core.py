def test_project_conflicts_missing_pdfs_alias_paths_and_integrity_preserve_history(
    tmp_path: Path,
) -> None:
    """Stale saves, absent uploads and host-path requests fail without silently changing an
    existing draft.
    """
    raw = b"%PDF-inert signature-only source for admission tests"
    profile = Profile(tmp_path / "workspace")
    try:
        with pytest.raises(ValueError, match="library"):
            profile.store.save(authored(raw), None, 0)
        profile.store.upload("inert.pdf", raw)
        saved = profile.store.save(authored(raw), None, 0)
        with pytest.raises(Conflict):
            profile.store.save(authored(raw, revision="B"), saved["id"], 0)
        with pytest.raises(Conflict):
            profile.store.project(saved["id"], 0)
        invalid = authored(raw)
        invalid["registry"]["sources"][0]["path"] = "../../outside.pdf"
        with pytest.raises(ValueError):
            profile.store.save(invalid, saved["id"], 1)
        assert profile.store.project(saved["id"]) == saved
        with profile.store.connect() as database:
            database.execute("UPDATE pdfs SET data=?", (b"%PDF-changed",))
        with pytest.raises(ValueError, match="integrity"):
            profile.store.files(ProjectInput.model_validate(saved["input"]))
        assert profile.store.project(saved["id"]) == saved
    finally:
        profile.close()


def test_artifact_manifest_does_not_bless_extra_or_wrong_publication_files() -> None:
    """Independently authored minimal blocked output must match every actual byte and
    complete inventory.
    """
    report = canonical({"publication_allowed": False})
    notice = b"Blocked\n"
    rows = [
        {"path": name, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
        for name, raw in {
            "reports/migration-report.json": report,
            "PUBLICATION_BLOCKED.txt": notice,
        }.items()
    ]
    files = {
        "reports/migration-report.json": report,
        "PUBLICATION_BLOCKED.txt": notice,
        "build-manifest.json": canonical({"manifest_version": 1, "files": rows}),
    }
    assert checked_files(files)["publication_allowed"] is False
    for changed in [
        {**files, "site/index.html": b"invented approval"},
        {**files, "PUBLICATION_BLOCKED.txt": b"tampered"},
        {key: value for key, value in files.items() if key != "PUBLICATION_BLOCKED.txt"},
    ]:
        with pytest.raises(ValueError):
            checked_files(changed)


def test_portable_project_import_is_complete_atomic_and_does_not_adopt_ids(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A complete byte-bound snapshot imports as a new draft; corruption/quota preserve both
    workspaces.
    """
    raw = b"%PDF- portable source fixture"
    first, second = Profile(tmp_path / "first"), Profile(tmp_path / "second")
    try:
        first.store.upload("portable.pdf", raw)
        saved = first.store.save(authored(raw), None, 0)
        exported = first.store.export_project(saved["id"], 1)
        assert base64.b64decode(exported["files"][0]["base64"]) == raw
        bad = json.loads(canonical(exported))
        bad["files"][0]["base64"] = base64.b64encode(b"%PDF- substituted").decode()
        with pytest.raises(ValueError, match="identity"):
            second.store.import_project(bad)
        assert second.store.library() == [] and second.store.listing("projects") == []
        with monkeypatch.context() as changed:
            changed.setattr(store_module, "MAX_HISTORY", 1)
            with pytest.raises(ValueError, match="256 MiB"):
                second.store.import_project(exported)
        assert second.store.library() == [] and second.store.listing("projects") == []
        imported = second.store.import_project(exported)
        assert imported["id"] != saved["id"] and imported["revision"] == 1
        assert imported["input"] == saved["input"]
        assert second.store.export_project(imported["id"], 1) == exported
        with pytest.raises(Conflict):
            first.store.export_project(saved["id"], 0)
        digest = hashlib.sha256(raw).hexdigest()
        with pytest.raises(Conflict, match="referenced"):
            second.store.remove_pdf(digest)
        with pytest.raises(Conflict):
            second.store.remove_project(imported["id"], 0)
        second.store.remove_project(imported["id"], 1)
        second.store.remove_pdf(digest)
        assert second.store.library() == [] and second.store.listing("projects") == []
        assert first.store.project(saved["id"]) == saved
    finally:
        first.close()
        second.close()
