def authored(raw: bytes, *, revision: str = "A", checksum: str | None = None) -> dict[str, Any]:
    """Use actual supplied bytes with a separate editable declared checksum/revision policy."""
    digest = hashlib.sha256(raw).hexdigest()
    return {
        "title": "Calibration%_ maintenance package",
        "registry": {
            "registry_version": 1,
            "sources": [
                {
                    "source_id": "calibration-manual",
                    "revision": revision,
                    "product_model": "Synthetic service instrument",
                    "owner": "Synthetic maintenance team",
                    "license": "MIT original synthetic fixture",
                    "path": "sources/" + digest + ".pdf",
                    "sha256": checksum,
                    "migration_status": "in-review",
                }
            ],
        },
        "limits": {"max_pages": 10, "max_blocks_per_page": 500, "heading_ratio": 1.25},
    }


def actual_engine(root: Path, *, timeout: float = 60) -> Engine:
    """Use this interpreter and original engine through the real fixed child entry, not a
    fake API.
    """
    environment = dict(os.environ)
    environment.pop("PYMUPDF_SUGGEST_LAYOUT_ANALYZER", None)
    return Engine(
        [sys.executable, "-I", str(root / "launcher.py"), "--engine-job"],
        {
            "product": "engineering-documentation-foundry",
            "version": "0.2.0",
            "sourceCommit": "development",
        },
        environment,
        timeout=timeout,
    )


def test_actual_pdf_build_exact_exports_blocked_checksum_and_durable_history(
    tmp_path: Path,
    repository_root: Path,
) -> None:
    """A real calibration PDF publishes deterministically; wrong expected bytes retain
    blocked review only.
    """
    raw = (repository_root / "examples/sources/sensor-calibration.pdf").read_bytes()
    name, data, digest = pdf_upload("custom-service.pdf", base64.b64encode(raw).decode())
    profile = Profile(tmp_path / "workspace")
    try:
        library = profile.store.upload(name, data)
        assert library["sha256"] == digest and library["bytes"] == len(raw)
        saved = profile.store.save(authored(raw, checksum=digest), None, 0)
        project = ProjectInput.model_validate(saved["input"])
        report, archive, identity = actual_engine(repository_root).run(
            project, profile.store.files(project)
        )
        assert report["publication_allowed"] is True and report["source_count"] == 1
        assert report["topic_count"] >= 2
        files = unpack(archive)
        topics = json.loads(files["canonical/topics.json"])
        assert all(
            topic["source_id"] == "calibration-manual" and topic["source_revision"] == "A"
            for topic in topics
        )
        blocks = [block for topic in topics for block in topic["blocks"]]
        assert any(
            block["table_rows"][0] == ["Reference", "Expected", "Tolerance"]
            for block in blocks
            if block["kind"] == "table"
        )
        notices = [block["warning"] for block in blocks if block["warning"] is not None]
        assert len(notices) == 1 and notices[0]["condition"] == "port is pressurized"
        assert (
            notices[0]["consequence"] == "fluid release"
            and notices[0]["avoidance"] == "vent the port"
        )
        assert report["documents"][0]["page_count"] == 2
        assert {block["provenance"]["page"] for block in blocks} == {1, 2}
        assert all(len(block["provenance"]["bbox"]) == 4 for block in blocks)
        assert b"calibration-manual" in files["site/index.html"]
        assert "pymupdf_layout" in identity["worker_diagnostics"]
        again, same, _ = actual_engine(repository_root).run(project, profile.store.files(project))
        assert again == report and same == archive
        first = profile.store.retain_build(saved, report, archive, identity)
        revised = profile.store.save(authored(raw, revision="B", checksum="0" * 64), saved["id"], 1)
        next_input = ProjectInput.model_validate(revised["input"])
        blocked, blocked_zip, provenance = actual_engine(repository_root).run(
            next_input, profile.store.files(next_input)
        )
        assert blocked["publication_allowed"] is False and blocked["issue_counts"]["error"] == 1
        blocked_files = unpack(blocked_zip)
        assert "PUBLICATION_BLOCKED.txt" in blocked_files and not any(
            name.startswith("site/") for name in blocked_files
        )
        second = profile.store.retain_build(revised, blocked, blocked_zip, provenance)
        assert second["status"] == "blocked" and first["status"] == "published"
        assert profile.store.build(first["id"])["input"] == saved["input"]
        assert profile.store.listing("projects", "%_")[0]["revision"] == 2
        assert len(profile.store.listing("builds", status="blocked")) == 1
        identifiers = first["id"], second["id"], saved["id"]
    finally:
        profile.close()
    reopened = Profile(tmp_path / "workspace")
    try:
        assert len(reopened.store.listing("builds")) == 2
        assert reopened.store.build(identifiers[0], with_bundle=True)["bundle"] == archive
        assert reopened.store.build(identifiers[1])["status"] == "blocked"
        assert reopened.store.project(identifiers[2])["revision"] == 2
    finally:
        reopened.close()


