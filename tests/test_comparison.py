def topic(identifier: str = "source.start", source: str = "source", warning: bool = False) -> Topic:
    """Create a realistic cited coolant-maintenance topic with optional complete safety notice."""
    block = {
        "kind": "warning" if warning else "paragraph",
        "text": "Isolate the coolant loop.",
        "provenance": {"page": 2, "bbox": [10, 20, 100, 50]},
        "source_block_id": "source.p2.b1",
    }
    if warning:
        block["warning"] = {
            "severity": "warning",
            "condition": "hot coolant is pressurized",
            "consequence": "burns",
            "avoidance": "isolate, cool and depressurize before service",
        }
    return Topic.model_validate(
        {
            "topic_id": identifier,
            "title": "Coolant service",
            "content_type": "task",
            "source_id": source,
            "source_revision": "1",
            "blocks": [block],
        }
    )


def corpus(path: Path, topics: tuple[Topic, ...]) -> Path:
    """Write canonical schema data selected explicitly by the reviewer."""
    path.write_text(json.dumps([item.model_dump(mode="json") for item in topics]), encoding="utf-8")
    return path


def test_reviewer_sees_exact_content_revision_provenance_and_safety_changes() -> None:
    """Differentiate changed advice, revision-only labels and relocated source citations."""
    original = topic(warning=True)
    payload = original.model_dump(mode="json")
    payload["source_revision"] = "2"
    payload["blocks"][0]["warning"]["avoidance"] = "isolate and wait until the gauge reads zero"
    payload["blocks"][0]["provenance"]["page"] = 3
    changed = Topic.model_validate(payload)
    report = compare_topics((original,), (changed,))
    assert report["counts"] == {"added": 0, "removed": 0, "changed": 1, "unchanged": 0}
    change = report["changes"][0]
    assert change["changed_fields"] == ["content", "source_revision", "provenance"]
    assert change["safety_review_required"] is True
    assert change["before"]["blocks"][0]["provenance"]["page"] == 2
    assert change["after"]["blocks"][0]["warning"]["avoidance"].endswith("zero")
    revision = original.model_copy(update={"source_revision": "2"})
    revision_change = compare_topics((original,), (revision,))["changes"][0]
    assert revision_change["changed_fields"] == ["source_revision"]
    assert revision_change["safety_review_required"] is False


def test_renames_removals_duplicate_titles_and_empty_corpus_are_not_inferred() -> None:
    """Match stable identities only, preserving removed notices and distinct sources."""
    original = topic(warning=True)
    renamed = original.model_copy(update={"topic_id": "source.revised"})
    other = topic("source.start", "different-source")
    report = compare_topics((original, other), (renamed, other))
    assert report["counts"] == {"added": 1, "removed": 1, "changed": 0, "unchanged": 1}
    assert all(change["safety_review_required"] for change in report["changes"])
    assert compare_topics((original,), ())["counts"]["removed"] == 1
    assert compare_topics((), ())["changes"] == []
    with pytest.raises(ValueError, match="duplicate"):
        compare_topics((original, original), ())


def test_order_and_json_whitespace_do_not_change_dossier(tmp_path: Path) -> None:
    """Corpus order is irrelevant while changed content affects its canonical digest."""
    first, second = topic(), topic("other.topic", "other")
    assert compare_topics((first, second), (second, first))["changes"] == []
    assert (
        compare_topics((first, second), (second, first))["before_sha256"]
        == compare_topics((second, first), (first, second))["after_sha256"]
    )
    file = corpus(tmp_path / "topics.json", (first,))
    file.write_text("\n " + file.read_text(encoding="utf-8") + "\n", encoding="utf-8")
    assert load_topics(file) == (first,)


@pytest.mark.parametrize("payload", [b"{}", b"[", b"\xff", b'{"a":1,"a":2}', b"[{}]", b"[" * 2000])
def test_malformed_corpus_rejected_before_creating_output(tmp_path: Path, payload: bytes) -> None:
    """Malformed UTF-8, JSON, duplicated keys, recursion and unknown schemas fail explicitly."""
    before = tmp_path / "before.json"
    before.write_bytes(payload)
    after = corpus(tmp_path / "after.json", ())
    with pytest.raises(ValueError):
        write_comparison(before, after, tmp_path / "review")
    assert not (tmp_path / "review").exists()


def test_size_count_duplicate_and_unknown_fields_rejected(tmp_path: Path) -> None:
    """Enforce actual byte/count/schema limits and do not silently collapse duplicate identities."""
    path = tmp_path / "topics.json"
    path.write_bytes(b" " * (MAX_CORPUS_BYTES + 1))
    with pytest.raises(ValueError, match="16 MiB"):
        load_topics(path)
    path.write_text(json.dumps([None] * 10_001), encoding="utf-8")
    with pytest.raises(ValueError, match="10,000"):
        load_topics(path)
    corpus(path, (topic(), topic()))
    with pytest.raises(ValueError, match="duplicate"):
        load_topics(path)
    path.write_text(
        json.dumps([{**topic().model_dump(mode="json"), "ignored": "no"}]), encoding="utf-8"
    )
    with pytest.raises(ValueError, match="ignored"):
        load_topics(path)


def test_actual_cli_review_is_deterministic_escaped_and_never_overwrites(tmp_path: Path) -> None:
    """A reviewer opens usable HTML and JSON, gets a gate code, and retains both source files."""
    original = topic(warning=True)
    payload = original.model_dump(mode="json")
    payload["blocks"].append(
        {
            "kind": "table",
            "text": "Service limits",
            "source_block_id": "source.p2.b2",
            "provenance": {"page": 2, "bbox": [10, 60, 100, 100]},
            "table_rows": [["Parameter", "Limit"], ["Coolant pressure", "0 kPa before opening"]],
        }
    )
    original = Topic.model_validate(payload)
    edited = original.model_copy(update={"title": "<script>alert('no')</script>"})
    before = corpus(tmp_path / "before.json", (original,))
    after = corpus(tmp_path / "after.json", (edited,))
    original_bytes = before.read_bytes(), after.read_bytes()
    output = tmp_path / "review"
    args = ["compare", str(before), str(after), "--output", str(output), "--fail-on-change"]
    assert main(args) == 2
    assert (before.read_bytes(), after.read_bytes()) == original_bytes
    html = (output / "comparison.html").read_text(encoding="utf-8")
    assert "<script>alert" not in html
    assert "&lt;script&gt;" in html
    assert "Before snapshot" in html and '"source_block_id"' in html
    assert "default-src 'none'" in html
    assert '<th scope="col">Parameter</th>' in html
    assert "<td>0 kPa before opening</td>" in html
    assert html.count("<dt>Avoidance</dt>") == 2
    dossier = json.loads((output / "comparison.json").read_text(encoding="utf-8"))
    assert dossier["changes"][0]["title"] == edited.title
    assert main(args) == 1
    assert (output / "comparison.html").read_text(encoding="utf-8") == html
    other = tmp_path / "review-again"
    assert main(["compare", str(before), str(after), "--output", str(other)]) == 0
    assert (other / "comparison.html").read_bytes() == (output / "comparison.html").read_bytes()
    assert (
        main(
            [
                "compare",
                str(before),
                str(before),
                "--output",
                str(tmp_path / "same"),
                "--fail-on-change",
            ]
        )
        == 0
    )
    assert (
        main(["compare", str(tmp_path / "missing"), str(after), "--output", str(tmp_path / "bad")])
        == 1
    )


def test_real_build_and_blocked_corpus_can_be_reviewed(
    tmp_path: Path, repository_root: Path
) -> None:
    """Review real published and blocked PDF-build artifacts without bypassing publication gates."""
    published = tmp_path / "published"
    run_pipeline(PipelineConfig(repository_root / "examples/source-registry.yaml", published))
    source = published / "canonical/topics.json"
    assert main(["compare", str(source), str(source), "--output", str(tmp_path / "identical")]) == 0
    (tmp_path / "bad.pdf").write_bytes(
        (repository_root / "tests/fixtures/malformed.pdf").read_bytes()
    )
    registry = tmp_path / "blocked-registry.json"
    registry.write_text(
        json.dumps(
            {
                "registry_version": 1,
                "sources": [
                    {
                        "source_id": "broken",
                        "revision": "1",
                        "product_model": "Coolant Controller",
                        "owner": "Synthetic QA",
                        "license": "MIT",
                        "path": "bad.pdf",
                    }
                ],
            }
        ),
        encoding="utf-8",
    )
    blocked = tmp_path / "blocked"
    with pytest.raises(PublicationBlocked):
        run_pipeline(PipelineConfig(registry, blocked))
    report = write_comparison(source, blocked / "canonical/topics.json", tmp_path / "removals")
    assert report["counts"]["removed"] >= 16
    assert any(change["safety_review_required"] for change in report["changes"])
    assert (published / "site/index.html").is_file()
    assert not (blocked / "site").exists()
