import pytest

from tools import runtime_notices


def test_exact_active_pins_and_original_notice_files_are_required(tmp_path, monkeypatch):
    """Evaluate real lock markers before checking independent installed-version metadata."""
    (tmp_path / "requirements.lock").write_text(
        "one==1.2.3 \\\n    --hash=sha256:fixture\nunused==1 ; python_version < '0'\n",
        encoding="utf-8",
    )
    (tmp_path / "requirements-package.lock").write_text("compatibility==4.5.6\n", encoding="utf-8")
    actual = {"one": "1.2.3", "compatibility": "4.5.6"}
    calls = []

    def distribution(name):
        """Reject any unselected platform dependency while returning its actual fixture version."""
        calls.append(name)
        return SimpleNamespace(version=actual[name])

    monkeypatch.setattr(runtime_notices, "distribution", distribution)
    assert runtime_notices.locked_distributions(tmp_path) == ["compatibility", "one"]
    assert calls == ["one", "compatibility"]
    actual["compatibility"] = "4.5.5"
    with pytest.raises(ValueError, match="differs from exact lock"):
        runtime_notices.locked_distributions(tmp_path)
    (tmp_path / "requirements.lock").write_text("# empty\n", encoding="utf-8")
    (tmp_path / "requirements-package.lock").write_text("# empty\n", encoding="utf-8")
    with pytest.raises(ValueError, match="inventory is empty"):
        runtime_notices.locked_distributions(tmp_path)


def test_attribution_inventory_keeps_complete_terms_and_refuses_bytecode(tmp_path):
    """AUTHORS and nonstandard LICENSE.APACHE remain in the actual package-shaped notice tree."""
    names = [
        Path("package.dist-info/licenses/LICENSE.APACHE"),
        Path("package.dist-info/licenses/AUTHORS.rst"),
        Path("package.dist-info/licenses/__pycache__/AUTHORS.pyc"),
        Path("package.dist-info/licenses/AUTHORS.py"),
    ]
    info = SimpleNamespace(files=names, locate_file=lambda name: tmp_path / name)
    assert runtime_notices.notice_paths(info) == [tmp_path / names[0], tmp_path / names[1]]
