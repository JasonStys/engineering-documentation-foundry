from __future__ import annotations

import sys
from pathlib import Path


def main() -> int:
    """Activate a previously verified native parser before importing the original engine."""
    arguments = sys.argv[1:]
    if arguments and arguments[0] == "--engine-job":
        if len(arguments) != 2:
            raise ValueError("The internal engine entry requires one owned fresh directory")
        protocol = sys.stdout.buffer
        # Upstream Python diagnostics (including atexit-buffered text) belong to
        # stderr. Keep the real protocol descriptor separate without filtering
        # any engine output or discarding its retained diagnostic transcript.
        sys.stdout = sys.stderr
        if getattr(sys, "frozen", False):
            from foundry_desktop import parser_setup
            from foundry_desktop.resources import load

            # Verify actual pins, static bytes and runtime before importing the dependency.
            load()

            parser_setup.activate(parser_setup.dependency_home(), parser_setup.selected_pin())
        from foundry_desktop.worker import main as worker

        return worker(Path(arguments[1]), protocol)
    from foundry_desktop.desktop import main as desktop

    return desktop(arguments)


if __name__ == "__main__":
    raise SystemExit(main())
