def launch(
    command: list[str], profile: Path, environment: dict[str, str]
) -> tuple[subprocess.Popen[str], dict[str, Any]]:
    """Read one bounded actual-ready record from a new process and independently verify its
    nonce.
    """
    process = subprocess.Popen(
        [*command, "--no-window", "--no-browser", "--profile", str(profile)],
        cwd=profile.parent,
        env=environment,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
    )
    require(
        process.stdout is not None and process.stderr is not None, "Actual process pipes missing"
    )
    events: queue.Queue[Any] = queue.Queue(maxsize=1)

    def read_ready() -> None:
        """Bound the readiness line before handing it to the waiting native consumer."""
        try:
            require(process.stdout is not None, "Actual stdout missing")
            line = process.stdout.readline(16385)
            require(0 < len(line) <= 16384, "Missing or oversized native readiness")
            events.put(json.loads(line), timeout=1)
        except Exception as error:
            events.put(error, timeout=1)

    thread = threading.Thread(target=read_ready, name="foundry-consumer-ready", daemon=True)
    thread.start()
    try:
        ready = events.get(timeout=20)
        require(
            isinstance(ready, dict) and ready.get("event") == "ready",
            "Native app did not become ready: " + str(ready),
        )
        target = urlsplit(ready["url"])
        require(
            target.scheme == "http"
            and target.hostname == "127.0.0.1"
            and target.port is not None
            and target.path == "",
            "Unexpected owned listener URL",
        )
        with httpx.Client(base_url=ready["url"], trust_env=False, timeout=5) as client:
            actual = client.get("/health").json()
            require(
                actual["nonce"] == ready["nonce"] and actual["identity"] == ready["identity"],
                "Owned identity/nonce does not match",
            )
        return process, ready
    except Exception:
        if process.poll() is None:
            process.kill()
        process.wait(timeout=5)
        diagnostic = process.stderr.read(65537) if process.stderr is not None else ""
        print(diagnostic, file=sys.stderr)
        raise
    finally:
        thread.join(timeout=1)


def close(process: subprocess.Popen[str], ready: dict[str, Any]) -> None:
    """Request normal Quit only from the actual nonce-bound listener; never terminate an
    unknown service.
    """
    if process.poll() is not None:
        return
    try:
        with httpx.Client(
            base_url=ready["url"],
            trust_env=False,
            timeout=5,
            headers={"Origin": ready["url"], "X-Foundry-Capability": ready["token"]},
        ) as client:
            require(
                client.get("/health").json()["nonce"] == ready["nonce"],
                "Refuse foreign listener cleanup",
            )
            require(
                client.post("/api/quit", json={"confirm": True}).status_code == 200,
                "Owned normal Quit refused",
            )
    except httpx.ConnectError:
        require(process.wait(timeout=20) == 0, "Already closing owner did not exit normally")
    else:
        require(process.wait(timeout=20) == 0, "Actual owner did not exit normally")


def stopped(process: subprocess.Popen[str], ready: dict[str, Any]) -> None:
    """Require the real stopped record after exit; upstream diagnostics remain separate."""
    require(
        process.returncode == 0 and process.stdout is not None,
        "Actual owner has not exited normally",
    )
    transcript = process.stdout.read(65537)
    require(len(transcript) <= 65536, "Unexpected owner diagnostic budget")
    records = [json.loads(line) for line in transcript.splitlines() if line.startswith('{"event":')]
    require(
        records == [{"event": "stopped", "nonce": ready["nonce"], "normal": True}],
        "Actual stopped ownership record differs",
    )


def held_publication(
    process: subprocess.Popen[str], ready: dict[str, Any], saved: dict[str, Any]
) -> dict[str, Any]:
    """Admit a PDF build, request Quit, then require real completion after releasing its body."""
    port = urlsplit(ready["url"]).port
    body = json.dumps({"id": saved["id"], "revision": saved["revision"]}).encode()
    with socket.create_connection(("127.0.0.1", port), timeout=5) as stream:
        stream.sendall(
            (
                "POST /api/build HTTP/1.1\r\n"
                + f"Host: 127.0.0.1:{port}\r\nOrigin: {ready['url']}\r\n"
                + f"X-Foundry-Capability: {ready['token']}\r\n"
                + "Content-Type: application/json\r\n"
                + f"Content-Length: {len(body)}\r\nExpect: 100-continue\r\n\r\n"
            ).encode()
        )
        header = bytearray()
        while not header.endswith(b"\r\n\r\n"):
            chunk = stream.recv(1)
            require(chunk and len(header) < 4096, "Actual admission handshake absent/oversized")
            header.extend(chunk)
        require(
            bytes(header) == b"HTTP/1.1 100 Continue\r\n\r\n", "Build was not actually admitted"
        )
        with httpx.Client(
            base_url=ready["url"],
            trust_env=False,
            timeout=5,
            headers={"Origin": ready["url"], "X-Foundry-Capability": ready["token"]},
        ) as client:
            require(
                client.post("/api/quit", json={"confirm": True}).status_code == 200,
                "Normal Quit refused",
            )
        require(
            process.poll() is None,
            "Owner exited before the admitted publication body/child completed",
        )
        stream.sendall(body)
        stream.settimeout(70)
        response = http.client.HTTPResponse(stream)
        response.begin()
        raw = response.read(1024 * 1024 + 1)
        require(
            response.status == 201 and len(raw) <= 1024 * 1024,
            "Admitted actual publication did not finish after Quit",
        )
        record = json.loads(raw)
        require(
            record["status"] == "published"
            and record["input"] == saved["input"]
            and record["revision"] == saved["revision"],
            "After-Quit build changed the admitted snapshot or claimed false publication",
        )
    require(process.wait(timeout=20) == 0, "Owner abandoned its accepted publication")
    return record


def inputs(output: Path) -> None:
    """Produce realistic independent revised documentation with known values and a complete
    changed notice.
    """
    original = (ROOT / "examples/sources/sensor-calibration.pdf").read_bytes()
    path = output / "authored-revision.pdf"
    canvas = Canvas(str(path), pagesize=(612, 792), invariant=True)
    canvas.setTitle("Synthetic revised calibration manual")
    canvas.setFont("Helvetica-Bold", 20)
    canvas.drawString(45, 740, "Pressure Sensor Calibration")
    canvas.setFont("Helvetica", 11)
    canvas.drawString(
        45, 705, "Confirm a reference pressure of 2.5 bar before recording the measured offset."
    )
    canvas.setFont("Helvetica", 9)
    canvas.drawString(
        45,
        675,
        (
            "CAUTION: condition=equipment is energized; consequence=electric shock;"
            " avoidance=disconnect power."
        ),
    )
    canvas.setFont("Helvetica-Bold", 16)
    canvas.drawString(45, 630, "Acceptance Criteria")
    canvas.setFont("Helvetica", 11)
    canvas.drawString(
        45,
        600,
        "Record the instrument identifier and verified reference value in the service log.",
    )
    canvas.save()
    custom = path.read_bytes()
    (output / "inputs.json").write_text(
        json.dumps(
            {
                "original": base64.b64encode(original).decode(),
                "custom": base64.b64encode(custom).decode(),
                "originalSha256": hashlib.sha256(original).hexdigest(),
                "customSha256": hashlib.sha256(custom).hexdigest(),
            }
        ),
        encoding="utf-8",
    )


def journey(
    command: list[str], output: Path, expected: dict[str, Any], environment: dict[str, str]
) -> None:
    """Run genuine author/build/review/export UI, then verify unchanged retained history
    after actual restart.
    """
    output.mkdir(parents=True, exist_ok=False)
    inputs(output)
    profile = output / "synthetic-workspace"
    processes: list[tuple[subprocess.Popen[str], dict[str, Any]]] = []
    try:
        process, ready = launch(command, profile, environment)
        processes.append((process, ready))
        require(
            ready["identity"]["sourceCommit"] == expected["sourceCommit"]
            and ready["identity"]["version"] == "0.2.0",
            "Actual runtime source/version mismatch",
        )
        node = shutil.which("node")
        require(node is not None, "QA Node runtime absent")
        subprocess.run(
            [
                node,
                str(ROOT / "tools/native_feature_smoke.mjs"),
                ready["url"] + "/#native=" + ready["token"],
                str(output),
                expected["sourceCommit"],
            ],
            cwd=output,
            env={**os.environ, **environment},
            check=True,
            timeout=150,
        )
        require(process.wait(timeout=20) == 0, "First actual owner did not exit normally")
        stopped(process, ready)
        browser = json.loads((output / "browser-acceptance.json").read_text())
        require(
            browser["passed"] is True and len(browser["records"]) == 3,
            "Actual three build journeys missing",
        )
        again, restarted = launch(command, profile, environment)
        processes.append((again, restarted))
        require(restarted["nonce"] != ready["nonce"], "Restart reused the previous owner")
        with httpx.Client(
            base_url=restarted["url"],
            trust_env=False,
            timeout=5,
            headers={
                "Origin": restarted["url"],
                "X-Foundry-Capability": restarted["token"],
            },
        ) as client:
            retained = client.get("/api/builds").json()
            require(
                {row["id"] for row in retained} == {row["id"] for row in browser["records"]},
                "Restart lost or fabricated historical builds",
            )
            for record in browser["records"]:
                actual = client.get("/api/detail", params={"id": record["id"]}).json()["build"]
                require(
                    all(
                        actual[key] == record[key]
                        for key in (
                            "id",
                            "revision",
                            "title",
                            "status",
                            "input",
                            "report",
                        )
                    ),
                    "Historical exact inputs/report changed on restart",
                )
                require(actual["sha"] == record["sha256"], "Historical artifact digest changed")
            require(
                len(client.get("/api/projects").json()) == 2,
                "Exact editable projects not retained",
            )
            saved = client.get("/api/project", params={"id": browser["originalProject"]}).json()
        after_quit = held_publication(again, restarted, saved)
        stopped(again, restarted)
        third, third_ready = launch(command, profile, environment)
        processes.append((third, third_ready))
        with httpx.Client(
            base_url=third_ready["url"],
            trust_env=False,
            timeout=5,
            headers={"Origin": third_ready["url"], "X-Foundry-Capability": third_ready["token"]},
        ) as client:
            actual = client.get("/api/detail", params={"id": after_quit["id"]}).json()["build"]
            require(
                actual == after_quit and len(client.get("/api/builds").json()) == 4,
                "Publication accepted before Quit was not durably retained exactly",
            )
        close(third, third_ready)
        stopped(third, third_ready)
        for _, owned_ready in processes:
            port = urlsplit(owned_ready["url"]).port
            try:
                socket.create_connection(("127.0.0.1", port), timeout=1).close()
            except OSError:
                continue
            raise ValueError("Actual owner left its listener running after normal exit")
        (output / "acceptance.json").write_text(
            json.dumps(
                {
                    "passed": True,
                    "version": "0.2.0",
                    "sourceCommit": expected["sourceCommit"],
                    "sourceDirty": expected["sourceDirty"],
                    "mode": "extracted compiled application"
                    if expected["sourceCommit"] != "development"
                    else "explicit source-only application",
                    "normalExits": [item.returncode for item, _ in processes],
                    "retainedActualBuilds": 4,
                    "originalBrowserBuilds": 3,
                    "acceptedPublicationCompletedAfterQuit": after_quit["id"],
                    "retainedEditableProjects": 2,
                    "browser": "actual Chromium",
                    "limits": (
                        "One synthetic OS-owner workspace; no installer transaction, "
                        "hostile-PDF sandbox, technical safety approval or manual OS-browser "
                        "opener claim"
                    ),
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
    finally:
        for process, ready in processes:
            close(process, ready)
            if process.stdout is not None:
                process.stdout.close()
            if process.stderr is not None:
                process.stderr.close()


def main() -> None:
    """Require a supplied extracted application and explicit setup consent before invoking
    native journeys.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("executable", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()
    executable = arguments.executable.resolve(strict=True)
    expected = json.loads((executable.parent / "RELEASE.json").read_text(encoding="utf-8"))
    require(
        expected["product"] == "engineering-documentation-foundry"
        and expected["version"] == "0.2.0",
        "Wrong supplied application",
    )
    output = arguments.output.resolve()
    require(not output.exists(), "Existing acceptance evidence preserved")
    # Keep the test's external Windows extension path comparable to a normal
    # per-user installation; a deeply nested source checkout is not that path.
    # The new empty directory is owned by this consumer and retained as evidence.
    home = Path(tempfile.mkdtemp(prefix="foundry-data-")).resolve(strict=True)
    environment = dict(os.environ)
    environment.pop("FOUNDRY_DEPENDENCY_HOME", None)
    if sys.platform == "win32":
        environment["LOCALAPPDATA"] = str(home)
        base = home
    elif sys.platform == "darwin":
        environment["HOME"] = str(home)
        base = home / "Library/Application Support"
    else:
        environment["XDG_DATA_HOME"] = str(home)
        base = home
    dependency = base / "JasonStysPortfolio/engineering-documentation-foundry/dependencies"
    setup = subprocess.run(
        [str(executable), "--setup-engine", "--no-window", "--no-browser"],
        cwd=output.parent,
        env=environment,
        input="INSTALL\n",
        text=True,
        encoding="utf-8",
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=120,
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    (output.parent / (output.name + "-explicit-setup.log")).write_text(
        setup.stdout, encoding="utf-8"
    )
    require(
        setup.returncode == 0
        and "GNU AGPL" in setup.stdout
        and "files.pythonhosted.org" in setup.stdout,
        "Actual explicit parser setup failed",
    )
    from foundry_desktop import parser_setup

    pin = parser_setup.selected_pin()
    require(
        parser_setup.installed(dependency, pin) is not None,
        "Actual official dependency failed independent offline verification",
    )
    journey([str(executable)], output, expected, environment)


if __name__ == "__main__":
    main()
