ROOT = Path(__file__).resolve().parents[1]
APPLICATION = "EngineeringDocumentationFoundry"


def digest(path: Path) -> str:
    """Hash the actual supplied file through one descriptor, without assuming metadata
    implies bytes.
    """
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def configuration(root: Path = ROOT) -> str:
    """Refuse mismatched product, Python package, editor lock or visible native version
    contracts.
    """
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    package = json.loads((root / "web/package.json").read_text(encoding="utf-8"))
    lock = json.loads((root / "web/package-lock.json").read_text(encoding="utf-8"))
    require(project["name"] == PRODUCT, "Wrong native product")
    require(
        project["version"]
        == package["version"]
        == lock["version"]
        == lock["packages"][""]["version"]
        == __version__,
        "Native version mismatch",
    )
    require(package["name"] == lock["name"] == PRODUCT + "-editor", "Editor identity mismatch")
    require(
        "Version " + __version__ in (root / "web/public/index.html").read_text(encoding="utf-8"),
        "Visible version mismatch",
    )
    require(re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", __version__), "Unknown version form")
    return __version__


def source_metadata(version: str, *, allow_dirty: bool = False) -> dict[str, Any]:
    """Bind the exact clean checkout in CI; explicitly label a local uncommitted candidate."""
    require(
        not allow_dirty or os.environ.get("GITHUB_ACTIONS") != "true",
        "CI forbids dirty candidates",
    )
    git = ["git", "-c", "safe.directory=" + ROOT.as_posix(), "-C", str(ROOT)]
    source = subprocess.check_output([*git, "rev-parse", "HEAD"], text=True).strip()
    status = subprocess.check_output(
        [*git, "status", "--porcelain", "--untracked-files=all"], text=True
    )
    require(re.fullmatch(r"[a-f0-9]{40}", source), "Invalid source identity")
    require(
        not status or allow_dirty,
        "Clean source required; use an explicitly labelled local candidate only",
    )
    if os.environ.get("GITHUB_ACTIONS") == "true":
        require(os.environ.get("GITHUB_SHA") == source, "Hosted source/checkout mismatch")
    return {
        "schema_version": 1,
        "product": PRODUCT,
        "version": version,
        "sourceCommit": source,
        "sourceDirty": bool(status),
        "platform": platform.system().lower(),
        "machine": platform.machine().lower(),
        "pythonVersion": platform.python_version(),
    }


def parser_free_inventory(bundle: Path, modules: Any) -> dict[str, int]:
    """Refuse actual frozen PyMuPDF/fitz modules and recognizable parser shared libraries or
    metadata.
    """
    modules = list(modules)
    require(
        not any(
            name == "fitz"
            or name.startswith("fitz.")
            or name == "pymupdf"
            or name.startswith("pymupdf.")
            for name in modules
        ),
        "PDF parser code was unexpectedly frozen",
    )
    authored = {"docfoundry", "foundry_desktop"}
    runtime = {
        "annotated_types",
        "jinja2",
        "markupsafe",
        "pydantic",
        "pydantic_core",
        "typing_extensions",
        "typing_inspection",
        "yaml",
        # PyInstaller's pinned compatibility graph can retain these modules;
        # the notice collector verifies both exact locks and retains their terms.
        "setuptools",
        "_distutils_hack",
        "packaging",
    }
    actual = {name.split(".")[0] for name in modules}
    configuration_modules = {sysconfig._get_sysconfigdata_name()} if os.name == "posix" else set()
    require(
        actual <= sys.stdlib_module_names | configuration_modules | authored | runtime,
        "Unreviewed development/runtime dependency was unexpectedly frozen",
    )
    visited = 0
    for path in bundle.rglob("*"):
        visited += 1
        relative = path.relative_to(bundle).as_posix().casefold()
        require(
            not any(
                part in {"pymupdf", "pymupdf.libs", "fitz"}
                or (part.startswith("pymupdf-") and part.endswith(".dist-info"))
                for part in relative.split("/")
            )
            and path.suffix.casefold() != ".whl"
            and not re.search("(?:^|lib|_)mupdf.*[.](?:dll|so|dylib|pyd)", path.name.casefold()),
            "PDF parser binary/metadata was unexpectedly bundled",
        )
    return {
        "embeddedModulesChecked": len(modules),
        "bundleEntriesChecked": visited,
        "embeddedParserModules": 0,
        "bundledParserPayloads": 0,
    }


def main() -> int:
    """Freeze only current Python, retain real notices, and exercise the archive actually
    produced.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument(
        "--allow-dirty",
        action="store_true",
        help="Explicit local candidate only; forbidden in CI",
    )
    arguments = parser.parse_args()
    require(
        supported_python(tuple(sys.version_info[:3]), sys.version_info.releaselevel),
        "Freeze requires final Python3.14.10 or a later 3.14 security patch",
    )
    output = arguments.output_root.absolute()
    require(
        not output.exists() and output.parent.resolve() == output.parent,
        "Choose a new canonical output folder",
    )
    version = configuration()
    source = source_metadata(version, allow_dirty=arguments.allow_dirty)
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            str(ROOT / "tests/test_runtime_notices.py"),
            "--capture=sys",
            "-q",
        ],
        cwd=ROOT,
        check=True,
        timeout=45,
    )
    web = ROOT / "web/dist"
    require(all((web / name).is_file() for name in ASSETS), "Build the actual editor first")
    pin_file = ROOT / "src/foundry_desktop/resources/pymupdf-wheels.json"
    output.mkdir()
    freeze = output / "freeze-environment"
    subprocess.run([sys.executable, "-m", "venv", str(freeze)], check=True, timeout=60)
    freeze_python = freeze / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
    subprocess.run(
        [
            str(freeze_python),
            "-m",
            "pip",
            "install",
            "--only-binary=:all:",
            "--require-hashes",
            "-r",
            str(ROOT / "requirements.lock"),
            "-r",
            str(ROOT / "requirements-package.lock"),
        ],
        check=True,
        timeout=180,
    )
    generated = output / "metadata"
    generated.mkdir()
    notice_contract = json.loads(
        (ROOT / ".runtime/notices-contract.json").read_text(encoding="utf-8")
    )
    require(
        notice_contract["passed"] is True
        and notice_contract["case_count"] == 13
        and notice_contract["interpreter"] == platform.python_version()
        and notice_contract["case_source_sha256"] == digest(ROOT / "tests/runtime_notice_cases.py")
        and notice_contract["reader_source_sha256"] == digest(ROOT / "tools/runtime_notices.py"),
        "Mandatory actual notice contract/source identity differs",
    )
    shutil.copyfile(ROOT / ".runtime/notices-contract.json", output / "notices-contract.json")
    # Read actual notices from the minimal freezing environment. Developer-only
    # optional packages must neither alter the bundle nor lose their attribution.
    subprocess.run(
        [str(freeze_python), "-m", "tools.runtime_notices", str(generated)],
        cwd=ROOT,
        check=True,
        timeout=30,
    )
    versions = json.loads((generated / "gui-versions.json").read_text(encoding="utf-8"))
    metadata = {
        **source,
        **versions,
        "assets": {name: digest(web / name) for name in ASSETS},
        "examples": {name: digest(ROOT / "examples/sources" / name) for name in EXAMPLES},
        "parserPinsSha256": digest(pin_file),
        "parserDistribution": "external official wheel; explicit consent required; not bundled",
    }
    if sys.platform == "win32":
        metadata["pythonRuntimeSha256"] = digest(Path(sys.base_prefix) / "python314.dll")
    identity = generated / "RELEASE.json"
    identity.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    terms = generated / "RUNTIME_NOTICES.txt"
    command = [
        str(freeze_python),
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--console",
        "--name",
        APPLICATION,
        "--exclude-module",
        "pymupdf",
        "--exclude-module",
        "fitz",
        "--paths",
        str(ROOT / "src"),
        "--distpath",
        str(output / "build"),
        "--workpath",
        str(output / "pyinstaller"),
        "--specpath",
        str(output),
    ]
    for path, destination in [
        (web, "web"),
        (identity, "."),
        (terms, "licenses"),
        (ROOT / "LICENSE", "licenses/project"),
        (ROOT / "licenses/PYTHON.txt", "licenses/python"),
        (ROOT / "docs/PDF_ENGINE_SETUP.md", "licenses/parser-setup"),
        (pin_file, "foundry_desktop/resources"),
    ]:
        command += ["--add-data", str(path) + ":" + destination]
    for name in EXAMPLES:
        command += ["--add-data", str(ROOT / "examples/sources" / name) + ":examples"]
    command += [str(ROOT / "launcher.py")]
    subprocess.run(
        command,
        cwd=ROOT,
        env={**os.environ, "PYINSTALLER_CONFIG_DIR": str(ROOT / ".runtime/pyinstaller-cache")},
        check=True,
        timeout=600,
    )
    require(
        source_metadata(version, allow_dirty=arguments.allow_dirty) == source,
        "Source changed while freezing",
    )
    bundle = output / "build" / APPLICATION
    executable = bundle / (APPLICATION + (".exe" if sys.platform == "win32" else ""))
    from PyInstaller.archive.readers import CArchiveReader

    embedded = CArchiveReader(str(executable)).open_embedded_archive("PYZ.pyz")
    inventory = parser_free_inventory(bundle, embedded.toc)
    if sys.platform == "win32":
        require(
            digest(bundle / "_internal/python314.dll") == metadata["pythonRuntimeSha256"],
            "Collected Python differs from the patched SDK",
        )
    shutil.copyfile(identity, bundle / "RELEASE.json")
    suffix = ".zip" if sys.platform == "win32" else ".tar.gz"
    archive = output / f"{PRODUCT}-v{version}-{source['platform']}-{source['machine']}{suffix}"
    create_archive(bundle, archive)
    require(archive_metadata(archive, APPLICATION) == metadata, "Actual archive metadata differs")
    (output / "parser-free-build.json").write_text(
        json.dumps({"source": metadata, **inventory}, indent=2) + "\n", encoding="utf-8"
    )
    with tempfile.TemporaryDirectory(prefix="foundry-owned-extracted-") as temporary:
        extracted = extract_archive(archive, Path(temporary).resolve() / "unpacked", APPLICATION)
        actual = extracted / (APPLICATION + (".exe" if sys.platform == "win32" else ""))
        subprocess.run(
            [
                sys.executable,
                str(ROOT / "tools/smoke_app.py"),
                str(actual),
                "--output",
                str(output / "acceptance"),
            ],
            cwd=temporary,
            check=True,
            timeout=300,
        )
    checksum = output / (archive.name + ".sha256")
    with checksum.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(digest(archive) + "  " + archive.name + "\n")
    print("Actual extracted full Foundry application passed: " + archive.name, flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
