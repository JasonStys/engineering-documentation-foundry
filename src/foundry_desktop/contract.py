from __future__ import annotations

import base64
import hashlib
import json
import re
from typing import Annotated, Any

from pydantic import BaseModel, ConfigDict, Field, StrictInt, StrictStr, field_validator

from docfoundry.models import SourceRegistry

PRODUCT = "engineering-documentation-foundry"
MAX_PDF = 8 * 1024 * 1024
MAX_SOURCE_BYTES = 32 * 1024 * 1024
MAX_REQUEST = 48 * 1024 * 1024
MAX_OUTPUT = 64 * 1024 * 1024
JSON = dict[str, Any]


def canonical(value: Any) -> bytes:
    """Bind complete submitted values rather than whitespace or JSON insertion order."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def unique(pairs: list[tuple[str, Any]]) -> JSON:
    """Reject duplicate keys before a signed-looking last value could conceal another input."""
    result: JSON = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON key")
        result[key] = value
    return result


def parsed(raw: bytes) -> Any:
    """Parse finite JSON with a byte and iterative nesting bound before model validation."""
    if len(raw) > MAX_REQUEST:
        raise ValueError("Input exceeds the 48 MiB request limit")
    try:
        value = json.loads(raw, object_pairs_hook=unique)
    except (ValueError, RecursionError) as error:
        raise ValueError("Use unambiguous bounded UTF-8 JSON: " + str(error)) from error
    pending = [(value, 0)]
    while pending:
        node, depth = pending.pop()
        if depth > 40:
            raise ValueError("JSON nesting exceeds 40 levels")
        if isinstance(node, dict):
            pending.extend((child, depth + 1) for child in node.values())
        elif isinstance(node, list):
            pending.extend((child, depth + 1) for child in node)
        elif isinstance(node, float) and (node != node or abs(node) == float("inf")):
            raise ValueError("Nonfinite JSON values are not supported")
    return value


class ClosedModel(BaseModel):
    """Forbid unknown native options; original engine models still validate source metadata."""

    model_config = ConfigDict(extra="forbid", frozen=True)


class Limits(ClosedModel):
    """Editable limits narrow the original PDF engine; they cannot disable its guards."""

    max_pages: Annotated[StrictInt, Field(ge=1, le=100)] = 100
    max_blocks_per_page: Annotated[StrictInt, Field(ge=1, le=5000)] = 5000
    heading_ratio: Annotated[float, Field(strict=True, ge=1.05, le=3, allow_inf_nan=False)] = 1.25


class ProjectInput(ClosedModel):
    """A complete authoring snapshot referencing exact uploaded PDF hashes, never host paths."""

    title: Annotated[StrictStr, Field(min_length=1, max_length=100)]
    registry: SourceRegistry
    limits: Limits = Field(default_factory=Limits)

    @field_validator("registry", mode="before")
    @classmethod
    def explicit_registry_version(cls, value: Any) -> Any:
        """Keep JSON booleans from being interpreted as the integer registry schema version."""
        if isinstance(value, SourceRegistry):
            return value
        if (
            not isinstance(value, dict)
            or type(value.get("registry_version")) is not int
            or value["registry_version"] != 1
        ):
            raise ValueError("Registry schema version must be integer 1")
        return value

    @field_validator("title")
    @classmethod
    def title_is_visible(cls, value: str) -> str:
        """Keep user titles literal and visible without interpreting their markup."""
        value = value.strip()
        if not value or any(ord(char) < 32 for char in value):
            raise ValueError("Give the project a visible title without control characters")
        return value

    @field_validator("registry")
    @classmethod
    def registered_files_are_owned(cls, value: SourceRegistry) -> SourceRegistry:
        """Require one to twelve immutable library members while keeping declared checksum
        policy.

        """
        if len(value.sources) > 12:
            raise ValueError("A native project supports at most 12 PDF sources")
        for source in value.sources:
            if re.fullmatch(r"sources/[a-f0-9]{64}[.]pdf", source.path) is None:
                raise ValueError(
                    "Choose an uploaded PDF; source paths must be its exact library hash"
                )
        return value

    def hashes(self) -> set[str]:
        """Return each unique actual PDF identity independently of source IDs or expected
        checksums.

        """
        return {
            source.path.removeprefix("sources/").removesuffix(".pdf")
            for source in self.registry.sources
        }


def pdf_upload(name: Any, encoded: Any) -> tuple[str, bytes, str]:
    """Bound/decode actual local bytes; a PDF signature is admission, not parser-safety approval."""
    if (
        not isinstance(name, str)
        or not 1 <= len(name) <= 120
        or not name.casefold().endswith(".pdf")
        or any(char in name for char in "\\/:")
        or any(ord(char) < 32 for char in name)
        or not isinstance(encoded, str)
        or len(encoded) > ((MAX_PDF + 2) // 3) * 4
    ):
        raise ValueError("Choose one local PDF filename and at most 8 MiB of bytes")
    raw = base64.b64decode(encoded, validate=True)
    if not 5 <= len(raw) <= MAX_PDF or not raw.startswith(b"%PDF-"):
        raise ValueError("The selected file is not a supported bounded PDF")
    return name, raw, hashlib.sha256(raw).hexdigest()


def object_fields(value: Any, fields: set[str]) -> JSON:
    """Require an exact API object so ignored switches cannot appear to have taken effect."""
    if not isinstance(value, dict) or set(value) != fields:
        raise ValueError("Unknown or missing request fields")
    return value


def opaque(value: Any) -> str:
    """Accept only generated database IDs; identifiers never select a filesystem path."""
    if not isinstance(value, str) or re.fullmatch(r"[a-f0-9]{32}", value) is None:
        raise ValueError("Invalid saved record identifier")
    return value


def project_input(value: Any) -> ProjectInput:
    """Parse raw editor text on the server so duplicate JSON fields cannot disappear in a
    browser parse.
    """
    if isinstance(value, str):
        value = parsed(value.encode("utf-8"))
    return ProjectInput.model_validate(value)
