from __future__ import annotations

import hashlib
import json
import os
import platform
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

from foundry_desktop import __version__
from foundry_desktop.private_io import bounded

if TYPE_CHECKING:
    from foundry_desktop.engine import Engine

PRODUCT = "engineering-documentation-foundry"
ASSETS = {
    "index.html": "text/html; charset=utf-8",
    "assets/app.js": "text/javascript; charset=utf-8",
    "assets/model.js": "text/javascript; charset=utf-8",
    "assets/styles.css": "text/css; charset=utf-8",
}
EXAMPLES = (
    "api-reference.pdf",
    "firmware-release-notes.pdf",
    "installation-procedure.pdf",
    "maintenance-checklist.pdf",
    "network-troubleshooting.pdf",
    "pump-controller-guide.pdf",
    "safety-and-specifications.pdf",
    "sensor-calibration.pdf",
)


def supported_python(version: tuple[int, ...], level: str) -> bool:
    """Keep the native security floor separate from the older supported CLI/source type target."""
    return len(version) >= 3 and version[:2] == (3, 14) and version[2] >= 10 and level == "final"


@dataclass(frozen=True)
class Resources:
    """Preloaded fixed resources and original-engine command; user inputs never choose these
    paths.

    """

    identity: dict[str, Any]
    assets: dict[str, tuple[str, bytes]]
    examples: dict[str, bytes]
    command: tuple[str, ...]
    environment: dict[str, str]

    def engine(self) -> Engine:
        """Import the original PDF engine only after explicit external-dependency activation."""
        from foundry_desktop.engine import Engine

        return Engine(self.command, self.identity, self.environment)


def load() -> Resources:
    """Verify native metadata and actual bytes or clearly label a repository development build."""
    frozen = bool(getattr(sys, "frozen", False))
    repository = Path(__file__).resolve().parents[2]
    root = Path(getattr(sys, "_MEIPASS", repository))
    if frozen:
        if not supported_python(tuple(sys.version_info[:3]), sys.version_info.releaselevel):
            raise ValueError(
                "Native application requires patched final Python 3.14.10 or later 3.14"
            )
        identity = json.loads(bounded(root / "RELEASE.json", 16384))
        if (
            not isinstance(identity, dict)
            or identity.get("product") != PRODUCT
            or identity.get("version") != __version__
            or identity.get("pythonVersion") != platform.python_version()
            or not isinstance(identity.get("sourceCommit"), str)
            or re.fullmatch(r"[a-f0-9]{40}", identity["sourceCommit"]) is None
            or type(identity.get("sourceDirty")) is not bool
        ):
            raise ValueError("Actual native product/version/source identity does not match")
        if not isinstance(identity.get("assets"), dict) or set(identity["assets"]) != set(ASSETS):
            raise ValueError("Actual native static inventory does not match")
        web, examples_root = root / "web", root / "examples"
        pins_file = root / "foundry_desktop/resources/pymupdf-wheels.json"
        if hashlib.sha256(bounded(pins_file, 8192)).hexdigest() != identity.get("parserPinsSha256"):
            raise ValueError("Native external-parser pins changed")
        if sys.platform == "win32" and hashlib.sha256(
            bounded(root / "python314.dll", 16 * 1024 * 1024)
        ).hexdigest() != identity.get("pythonRuntimeSha256"):
            raise ValueError("Native Python DLL differs from the verified patched runtime")
        command = [sys.executable, "--engine-job"]
    else:
        identity = {
            "product": PRODUCT,
            "version": __version__,
            "sourceCommit": "development",
            "sourceDirty": True,
            "pythonVersion": platform.python_version(),
        }
        web, examples_root = repository / "web/dist", repository / "examples/sources"
        command = [sys.executable, "-I", str(repository / "launcher.py"), "--engine-job"]
    assets = {}
    for name, media in ASSETS.items():
        raw = bounded(web / name, 512 * 1024)
        if frozen and hashlib.sha256(raw).hexdigest() != identity["assets"][name]:
            raise ValueError("Native GUI resource digest mismatch")
        assets["/" + name] = (media, raw)
    assets["/"] = assets["/index.html"]
    examples = {name: bounded(examples_root / name, 1024 * 1024) for name in EXAMPLES}
    if frozen and {
        name: hashlib.sha256(raw).hexdigest() for name, raw in examples.items()
    } != identity.get("examples"):
        raise ValueError("Native prepared source input bytes differ")
    # Fixed minimal child environment: documents cannot select PATH, proxies or PYTHONPATH.
    environment = {
        key: value
        for key, value in os.environ.items()
        if key.upper()
        in {
            "SYSTEMROOT",
            "WINDIR",
            "TEMP",
            "TMP",
            "HOME",
            "USERPROFILE",
            "LOCALAPPDATA",
            "LANG",
            "LC_ALL",
            "FOUNDRY_DEPENDENCY_HOME",
            "LD_LIBRARY_PATH",
            "DYLD_LIBRARY_PATH",
            "_PYI_APPLICATION_HOME_DIR",
            "_PYI_ARCHIVE_FILE",
            "_PYI_PARENT_PROCESS_LEVEL",
            "_PYI_LINUX_PROCESS_NAME",
        }
    }
    if sys.platform == "win32":
        system_root = Path(os.environ["SYSTEMROOT"])
        if not system_root.is_absolute():
            raise ValueError("The system directory must be absolute")
        environment["PATH"] = str(system_root / "System32")
    else:
        environment["PATH"] = "/usr/bin:/bin"
    return Resources(identity, assets, examples, tuple(command), environment)
