from __future__ import annotations

import base64
import hashlib
import subprocess
import tempfile
import threading
from collections.abc import Sequence
from pathlib import Path
from typing import BinaryIO

from foundry_desktop.artifacts import input_sha, pack
from foundry_desktop.contract import (
    JSON,
    MAX_REQUEST,
    MAX_SOURCE_BYTES,
    ProjectInput,
    canonical,
    object_fields,
    parsed,
)


class Engine:
    """A server-owned fixed argv; neither the registry nor an HTTP request can select a command."""

    def __init__(
        self,
        command: Sequence[str],
        identity: JSON,
        environment: dict[str, str],
        *,
        timeout: float = 60,
    ):
        """Bind approved application identity and an isolated child environment before
        accepting inputs.

        """
        self.command, self.identity, self.environment = list(command), identity, environment
        self.timeout = timeout

    def run(self, project: ProjectInput, files: dict[str, bytes]) -> tuple[JSON, bytes, JSON]:
        """Run actual PDF processing once, independently inspect output, then return complete
        evidence.

        """
        if set(files) != project.hashes() or sum(map(len, files.values())) > MAX_SOURCE_BYTES:
            raise ValueError("Actual source inventory differs or exceeds its byte limit")
        if any(hashlib.sha256(raw).hexdigest() != digest for digest, raw in files.items()):
            raise ValueError("Actual source bytes differ from their hash identities")
        snapshot = project.model_dump(mode="json")
        request = canonical(
            {
                "project": snapshot,
                "files": {key: base64.b64encode(value).decode() for key, value in files.items()},
            }
        )
        if len(request) > MAX_REQUEST:
            raise ValueError("Complete engine request exceeds its byte bound")
        with tempfile.TemporaryDirectory(prefix="foundry-owned-engine-") as temporary:
            job = Path(temporary).resolve(strict=True)
            completed, diagnostics = self._invoke(job, request)
            result = object_fields(
                parsed(completed),
                {"worker_schema", "project_sha256", "publication_allowed", "build_id"},
            )
            if (
                type(result["worker_schema"]) is not int
                or result["worker_schema"] != 1
                or result["project_sha256"] != input_sha(snapshot)
            ):
                raise ValueError("Actual engine response does not bind the submitted snapshot")
            report, archive = pack(job / "publication")
            if (
                result["publication_allowed"] is not report["publication_allowed"]
                or result["build_id"] != report["build_id"]
            ):
                raise ValueError("Actual output disagrees with its reported publication decision")
            return (
                report,
                archive,
                {
                    **self.identity,
                    "input_sha256": input_sha(snapshot),
                    "artifact_sha256": hashlib.sha256(archive).hexdigest(),
                    "worker_diagnostics": diagnostics.decode("utf-8", errors="replace"),
                },
            )

    def _invoke(self, job: Path, request: bytes) -> tuple[bytes, bytes]:
        """Collect bounded streams concurrently; every refusal waits for the exact owned
        child to exit.

        """
        process = subprocess.Popen(
            [*self.command, str(job)],
            cwd=job,
            env=self.environment,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        if process.stdin is None or process.stdout is None or process.stderr is None:
            process.kill()
            process.wait()
            raise RuntimeError("Owned worker pipes were not created")
        output, errors = bytearray(), bytearray()
        overflow = threading.Event()
        writer_errors: list[OSError] = []
        stop_lock = threading.Lock()

        def stop_owned() -> None:
            """Coordinate limit failures on only this Popen child; reap an already completed
            process.

            """
            with stop_lock:
                if process.poll() is None:
                    try:
                        process.kill()
                    except ProcessLookupError:
                        process.wait()

        def collect(pipe: BinaryIO, target: bytearray) -> None:
            """Refuse excess bytes as they arrive, without retaining an unbounded diagnostic
            transcript.

            """
            try:
                while chunk := pipe.read(16384):
                    if len(target) + len(chunk) > 65536:
                        overflow.set()
                        stop_owned()
                        break
                    target.extend(chunk)
            except OSError as error:
                writer_errors.append(error)
            finally:
                try:
                    pipe.close()
                except OSError as error:
                    writer_errors.append(error)

        def submit(pipe: BinaryIO) -> None:
            """Let the main waiter enforce the same finite deadline even during a blocked
            stdin write.

            """
            try:
                pipe.write(request)
                pipe.flush()
            except OSError as error:
                writer_errors.append(error)
            finally:
                try:
                    pipe.close()
                except OSError as error:
                    writer_errors.append(error)

        threads = [
            threading.Thread(
                target=collect, args=(process.stdout, output), name="foundry-worker-output"
            ),
            threading.Thread(
                target=collect, args=(process.stderr, errors), name="foundry-worker-errors"
            ),
            threading.Thread(target=submit, args=(process.stdin,), name="foundry-worker-input"),
        ]
        for thread in threads:
            thread.start()
        expired = False
        try:
            process.wait(timeout=self.timeout)
        except subprocess.TimeoutExpired:
            expired = True
            stop_owned()
            process.wait()
        finally:
            for thread in threads:
                thread.join()
        if expired:
            raise ValueError(
                "Original PDF engine exceeded the 60-second job deadline; no build was saved"
            )
        if overflow.is_set():
            raise ValueError("Original PDF engine exceeded its bounded response/diagnostic budget")
        if process.returncode != 0 or writer_errors:
            detail = bytes(errors).decode("utf-8", errors="replace")[:1200]
            raise ValueError("Original PDF processing failed; no build was saved. " + detail)
        return bytes(output), bytes(errors)
