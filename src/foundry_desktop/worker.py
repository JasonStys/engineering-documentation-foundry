from __future__ import annotations

import hashlib
import sys
from pathlib import Path
from typing import BinaryIO

from docfoundry.extractor import ExtractorConfig
from docfoundry.pipeline import PipelineConfig, PublicationBlocked, run_pipeline
from foundry_desktop.contract import (
    MAX_PDF,
    MAX_REQUEST,
    MAX_SOURCE_BYTES,
    ProjectInput,
    canonical,
    object_fields,
    parsed,
    pdf_upload,
)
from foundry_desktop.profile_paths import admitted_directory


def execute(directory: Path, raw: bytes) -> dict[str, object]:
    """Materialize only validated hash-named source bytes, then invoke the unchanged original
    engine.

    """
    directory = admitted_directory(directory)
    if not directory.is_dir() or any(directory.iterdir()):
        raise ValueError("An engine job requires a fresh empty dedicated directory")
    payload = object_fields(parsed(raw), {"project", "files"})
    project = ProjectInput.model_validate(payload["project"])
    files = payload["files"]
    if not isinstance(files, dict) or set(files) != project.hashes():
        raise ValueError("Submitted PDF inventory differs from the complete authored snapshot")
    sources = directory / "sources"
    sources.mkdir()
    total = 0
    for digest, encoded in files.items():
        _, data, actual = pdf_upload("source.pdf", encoded)
        total += len(data)
        if total > MAX_SOURCE_BYTES:
            raise ValueError("Actual PDF sources exceed the 32 MiB job limit")
        if actual != digest:
            raise ValueError("Source bytes differ from the submitted PDF identity")
        with (sources / (digest + ".pdf")).open("xb") as stream:
            stream.write(data)
    registry = directory / "source-registry.json"
    with registry.open("xb") as stream:
        stream.write(canonical(project.registry.model_dump(mode="json")))
    config = PipelineConfig(
        registry_path=registry,
        output_directory=directory / "publication",
        extractor=ExtractorConfig(
            max_file_bytes=MAX_PDF,
            max_pages=project.limits.max_pages,
            max_blocks_per_page=project.limits.max_blocks_per_page,
            heading_ratio=project.limits.heading_ratio,
        ),
    )
    try:
        report = run_pipeline(config)
    except PublicationBlocked as blocked:
        report = blocked.report
    return {
        "worker_schema": 1,
        "project_sha256": hashlib.sha256(canonical(project.model_dump(mode="json"))).hexdigest(),
        "publication_allowed": report.publication_allowed,
        "build_id": report.build_id,
    }


def main(directory: Path, protocol: BinaryIO) -> int:
    """Read a bounded stdin request and return one actual outcome; failures never look like
    publication.

    """
    try:
        raw = sys.stdin.buffer.read(MAX_REQUEST + 1)
        result = execute(directory, raw)
        protocol.write(canonical(result) + b"\n")
        protocol.flush()
        return 0
    except (ValueError, OSError, RuntimeError) as error:
        print(
            "The owned publication job failed: " + " ".join(str(error).split())[:1000],
            file=sys.stderr,
        )
        return 1
