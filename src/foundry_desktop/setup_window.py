def description(pin: dict[str, Any]) -> str:
    """Show the complete actual provider identity rather than a generic install reassurance."""
    return (
        f"Official PyPI dependency: PyMuPDF {parser_setup.VERSION}\n"
        f"File: {pin['filename']}\nBytes: {pin['bytes']:,}\nSHA256: {pin['sha256']}\n"
        f"ABI: {pin['tag']}\nExact URL: {pin['url']}"
    )


class DependencyWindow:
    """One real consent choice; no background writer is abandoned if the user closes during
    setup.

    """

    def __init__(self, root: tk.Tk, home: Path, pin: dict[str, Any]) -> None:
        """Keep the install/cancel actions visible while long upstream terms wrap and scroll."""
        self.root, self.home, self.pin = root, home, pin
        self.accepted = False
        self.cancel_requested = False
        self.thread: threading.Thread | None = None
        self.events: queue.Queue[str | None] = queue.Queue()
        root.title("Engineering Documentation Foundry | PDF engine setup | Jason Stys")
        root.geometry("790x650")
        root.minsize(700, 600)
        root.protocol("WM_DELETE_WINDOW", self.cancel)
        shell = ttk.Frame(root, padding=22)
        shell.pack(fill="both", expand=True)
        actions = ttk.Frame(shell)
        actions.pack(fill="x", side="bottom", pady=(14, 0))
        self.install_button = ttk.Button(
            actions, text="Install verified PDF engine", command=self.install
        )
        self.install_button.pack(side="left")
        self.cancel_button = ttk.Button(
            actions, text="Cancel without opening documents", command=self.cancel
        )
        self.cancel_button.pack(side="right")
        ttk.Label(
            shell, text="Enable the original local PDF engine", font=("TkDefaultFont", 16, "bold")
        ).pack(anchor="w")
        ttk.Label(shell, text="Jason Stys | explicit first-run dependency download").pack(
            anchor="w", pady=(6, 12)
        )
        self.text = tk.Text(shell, wrap="word", height=14, padx=10, pady=10)
        scrollbar = ttk.Scrollbar(shell, orient="vertical", command=self.text.yview)
        self.text.configure(yscrollcommand=scrollbar.set)
        scrollbar.pack(side="right", fill="y")
        self.text.pack(fill="both", expand=True)
        self.text.insert("1.0", TERMS + "\n\n" + description(pin))
        self.text.configure(state="disabled")
        self.status = tk.StringVar(value="No download has started. Choose Install or Cancel.")
        ttk.Label(shell, textvariable=self.status, wraplength=630).pack(anchor="w", pady=(12, 0))

    def install(self) -> None:
        """Only the explicit button starts one bounded download; no profile or PDF is opened."""
        if self.thread is not None:
            return
        self.install_button.configure(state="disabled")
        self.cancel_button.configure(state="disabled")
        self.status.set(
            "Downloading and verifying only the displayed wheel. No documents or "
            "workspace are open."
        )

        def run() -> None:
            """Return an ordinary setup failure while retaining ownership of this actual
            installer thread.

            """
            try:
                parser_setup.install(self.home, self.pin)
                self.events.put(None)
            except Exception as error:
                self.events.put(str(error))

        self.thread = threading.Thread(target=run, name="explicit-pdf-parser-install")
        self.thread.start()
        self.root.after(40, self.poll)

    def poll(self) -> None:
        """Show success only after the actual installer finishes and joins; polling never
        retries a fetch.

        """
        if self.thread is None:
            return
        if self.thread.is_alive():
            self.root.after(40, self.poll)
            return
        self.thread.join()
        error = self.events.get_nowait()
        if error is None:
            self.accepted = not self.cancel_requested
            self.root.destroy()
        else:
            self.status.set(
                "Setup failed; existing evidence was preserved. "
                + error
                + " Quit and reopen after correcting the cause."
            )
            self.cancel_button.configure(state="normal")

    def cancel(self) -> None:
        """Cancel before setup without network; retain an active writer until its bounded
        operation ends.

        """
        if self.thread is not None and self.thread.is_alive():
            self.cancel_requested = True
            self.status.set(
                "Finishing the already approved download, then closing without opening documents."
            )
            return
        self.root.destroy()


def ensure(*, interactive: bool = True, console: bool = False) -> bool:
    """Require a real GUI/console choice for an absent wheel; presence never replaces full
    verification.

    """
    pin, home = parser_setup.selected_pin(), parser_setup.dependency_home()
    if not parser_setup.has_installation(home, pin):
        if console:
            print(TERMS + "\n\n" + description(pin), flush=True)
            if (
                input(
                    "Type INSTALL to download exactly this dependency, or anything else to cancel: "
                )
                != "INSTALL"
            ):
                return False
            parser_setup.install(home, pin)
        elif interactive:
            root = tk.Tk()
            window = DependencyWindow(root, home, pin)
            root.mainloop()
            if not window.accepted:
                return False
        else:
            raise ValueError(
                "PDF engine is absent; open native setup or explicitly use --setup-engine"
            )
    parser_setup.activate(home, pin)
    return True
