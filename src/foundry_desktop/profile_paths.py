from __future__ import annotations

import os
import stat
import sys
from pathlib import Path


def member(path: Path, *, directory: bool = False) -> os.stat_result | None:
    """Inspect optional fixed members without following symbolic links or Windows reparse points."""
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None
    if (
        stat.S_ISLNK(info.st_mode)
        or getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0)
        or not (stat.S_ISDIR(info.st_mode) if directory else stat.S_ISREG(info.st_mode))
        or (not directory and info.st_nlink != 1)
    ):
        raise ValueError("Unsafe workspace member: choose ordinary unlinked files/directories")
    return info


def admitted_directory(path: Path) -> Path:
    """Check existing ancestors and actual frozen roots before any directory is made."""
    path = path.absolute()
    if ".." in path.parts:
        raise ValueError("Workspace parent traversal is not supported")
    for ancestor in (*reversed(path.parents), path):
        member(ancestor, directory=True)
    if getattr(sys, "frozen", False):
        executable = Path(sys.executable).resolve().parent
        roots = [executable, Path(getattr(sys, "_MEIPASS", executable)).resolve()]
        roots.extend(parent for parent in executable.parents if parent.suffix == ".app")
        if any(path.is_relative_to(root) for root in roots):
            raise ValueError("Keep private workspaces outside application installation files")
    return path


def workspace_members(directory: Path) -> None:
    """Refuse all fixed marker/lock/database/recovery aliases before opening a workspace."""
    for name in (
        "profile.json",
        "owner.lock",
        "workspace.sqlite3",
        "workspace.sqlite3-journal",
        "workspace.sqlite3-wal",
        "workspace.sqlite3-shm",
    ):
        member(directory / name)


def open_member(path: Path, flags: int, *, create: bool = False) -> int:
    """Recheck actual opened identity before writing; close even an unexpected fatal
    interruption.

    """
    prior = member(path)
    flags |= (
        getattr(os, "O_BINARY", 0) | getattr(os, "O_NONBLOCK", 0) | getattr(os, "O_NOFOLLOW", 0)
    )
    if prior is None:
        if not create:
            raise FileNotFoundError(path)
        flags |= os.O_CREAT | os.O_EXCL
    descriptor = os.open(path, flags, 0o600)
    accepted = False
    try:
        opened = os.fstat(descriptor)
        if (
            not stat.S_ISREG(opened.st_mode)
            or opened.st_nlink != 1
            or (
                prior is not None and (opened.st_dev, opened.st_ino) != (prior.st_dev, prior.st_ino)
            )
        ):
            raise ValueError("Workspace member identity changed while opening")
        accepted = True
        return descriptor
    finally:
        if not accepted:
            os.close(descriptor)
