from __future__ import annotations

import base64
import hashlib
import json
import tempfile
import threading
from pathlib import Path
from typing import Any

from docfoundry.comparison import write_comparison
from docfoundry.models import SourceRegistry, SourceSpec
from foundry_desktop.artifacts import unpack
from foundry_desktop.contract import (
    JSON,
    ProjectInput,
    object_fields,
    opaque,
    parsed,
    pdf_upload,
    project_input,
)
from foundry_desktop.private_io import bounded
from foundry_desktop.profile import Profile
from foundry_desktop.resources import Resources
from foundry_desktop.store import Conflict


class Service:
    """Per-workspace state and locks; no module-global data, external agent or arbitrary
    engine command.
    """

    def __init__(self, profile: Profile, resources: Resources) -> None:
        """Bind one already admitted profile and actual resource/engine identity after parser
        consent.
        """
        self.profile, self.resources = profile, resources
        self.store = profile.store
        self.engine = resources.engine()
        self.build_lock = threading.Lock()
        self.data_lock = threading.RLock()
        self.active_sources: set[str] = set()
        self.cache_lock = threading.Lock()
        self.cache_id: str | None = None
        self.cache_files: dict[str, bytes] = {}

    def build(self, value: Any) -> JSON:
        """Capture an exact saved revision and keep its actual PDF bytes referenced until the
        real job ends.
        """
        value = object_fields(value, {"id", "revision"})
        if type(value["revision"]) is not int or value["revision"] < 1:
            raise ValueError("Choose the explicit saved integer revision before building")
        if not self.build_lock.acquire(blocking=False):
            raise Conflict("A publication job is already running; this requested build has not run")
        try:
            with self.data_lock:
                saved = self.store.project(value["id"], value["revision"])
                project = ProjectInput.model_validate(saved["input"])
                files = self.store.files(project)
                self.active_sources = project.hashes()
            report, archive, identity = self.engine.run(project, files)
            with self.data_lock:
                return self.store.retain_build(saved, report, archive, identity)
        finally:
            with self.data_lock:
                self.active_sources.clear()
            self.build_lock.release()

    def publication(self, identifier: Any) -> tuple[JSON, dict[str, bytes]]:
        """Use one bounded immutable build cache, rehashing its stored ZIP before every
        selected lookup.
        """
        identifier = opaque(identifier)
        record = self.store.build(identifier, with_bundle=True)
        archive = record.pop("bundle")
        with self.cache_lock:
            if self.cache_id != identifier:
                self.cache_files = unpack(archive)
                self.cache_id = identifier
            return record, self.cache_files

    def detail(self, identifier: Any, query: str = "", kind: str = "", source: str = "") -> JSON:
        """Search real canonical text/table/notice content with explicit source and
        topic-type filters.
        """
        if (
            not isinstance(query, str)
            or len(query) > 100
            or kind not in ("", "concept", "task", "reference", "troubleshooting")
            or not isinstance(source, str)
            or len(source) > 64
        ):
            raise ValueError("Unsupported canonical topic filter")
        record, files = self.publication(identifier)
        topics = json.loads(files["canonical/topics.json"])
        if not isinstance(topics, list):
            raise ValueError("Canonical topic inventory is not a list")
        filtered = [
            topic
            for topic in topics
            if (not source or topic["source_id"] == source)
            and (not kind or topic["content_type"] == kind)
            and (not query or query.casefold() in json.dumps(topic, ensure_ascii=False).casefold())
        ]
        return {
            "build": record,
            "topic_total": len(topics),
            "topics": filtered,
            "sources": sorted({topic["source_id"] for topic in topics}),
            "artifacts": sorted(files),
        }

    def compare(self, value: Any) -> JSON:
        """Run the original cited corpus comparator on exact selected saved builds, never
        supplied reports.
        """
        value = object_fields(value, {"before", "after"})
        before, before_files = self.publication(value["before"])
        after, after_files = self.publication(value["after"])
        with tempfile.TemporaryDirectory(prefix="foundry-owned-review-") as temporary:
            directory = Path(temporary).resolve(strict=True)
            left, right = directory / "before.json", directory / "after.json"
            left.write_bytes(before_files["canonical/topics.json"])
            right.write_bytes(after_files["canonical/topics.json"])
            output = directory / "review"
            report = write_comparison(left, right, output)
            encoded = bounded(output / "comparison.json", 16 * 1024 * 1024).decode("utf-8")
            html = bounded(output / "comparison.html", 16 * 1024 * 1024).decode("utf-8")
        return {
            "before_build": before["id"],
            "after_build": after["id"],
            "report": report,
            "json": encoded,
            "html": html,
            "saved": False,
        }

    def action(self, path: str, value: Any) -> JSON:
        """Dispatch only closed authored actions; no endpoint accepts filesystem output paths
        or commands.
        """
        if path == "/api/validate":
            body = object_fields(value, {"input"})
            project = project_input(body["input"])
            files = self.store.files(project)
            return {
                "input": project.model_dump(mode="json"),
                "source_count": len(project.registry.sources),
                "unique_pdfs": len(files),
                "bytes": sum(map(len, files.values())),
                "pdfs_processed": False,
            }
        if path == "/api/append-source":
            body = object_fields(value, {"input", "metadata", "sha256", "pin_checksum"})
            if not isinstance(body["input"], str) or type(body["pin_checksum"]) is not bool:
                raise ValueError("Use raw project editor text and an explicit checksum choice")
            draft = object_fields(
                parsed(body["input"].encode("utf-8")), {"title", "registry", "limits"}
            )
            registry = object_fields(draft["registry"], {"registry_version", "sources"})
            if (
                type(registry["registry_version"]) is not int
                or registry["registry_version"] != 1
                or not isinstance(registry["sources"], list)
                or len(registry["sources"]) >= 12
            ):
                raise ValueError("A native draft has registry version 1 and at most 12 sources")
            metadata = object_fields(
                body["metadata"],
                {"source_id", "revision", "product_model", "owner", "license", "migration_status"},
            )
            if not isinstance(body["sha256"], str) or body["sha256"] not in {
                row["sha256"] for row in self.store.library()
            }:
                raise ValueError("Choose an uploaded source PDF")
            source = SourceSpec.model_validate(
                {
                    **metadata,
                    "path": "sources/" + body["sha256"] + ".pdf",
                    "sha256": body["sha256"] if body["pin_checksum"] else None,
                }
            )
            combined = SourceRegistry.model_validate(
                {
                    "registry_version": 1,
                    "sources": [*registry["sources"], source.model_dump(mode="json")],
                }
            )
            return {
                "input": {**draft, "registry": combined.model_dump(mode="json")},
                "saved": False,
                "pdfs_processed": False,
            }
        if path == "/api/upload":
            body = object_fields(value, {"name", "base64"})
            name, raw, _ = pdf_upload(body["name"], body["base64"])
            with self.data_lock:
                return self.store.upload(name, raw)
        if path == "/api/save":
            body = object_fields(value, {"id", "revision", "input"})
            with self.data_lock:
                return self.store.save(body["input"], body["id"], body["revision"])
        if path == "/api/import":
            if isinstance(value, str):
                value = parsed(value.encode("utf-8"))
            with self.data_lock:
                return self.store.import_project(value)
        if path == "/api/build":
            return self.build(value)
        if path == "/api/compare":
            return self.compare(value)
        if path == "/api/delete-project":
            body = object_fields(value, {"id", "revision"})
            with self.data_lock:
                self.store.remove_project(body["id"], body["revision"])
            return {"deleted": body["id"], "retained_builds_and_sources": True}
        if path == "/api/delete-build":
            body = object_fields(value, {"id"})
            self.store.remove_build(body["id"])
            with self.cache_lock:
                if self.cache_id == body["id"]:
                    self.cache_id, self.cache_files = None, {}
            return {"deleted": body["id"]}
        if path == "/api/delete-source":
            body = object_fields(value, {"sha256"})
            if (
                not isinstance(body["sha256"], str)
                or len(body["sha256"]) != 64
                or any(char not in "0123456789abcdef" for char in body["sha256"])
            ):
                raise ValueError("Invalid source PDF identity")
            with self.data_lock:
                if body["sha256"] in self.active_sources:
                    raise Conflict("The active publication job still owns these source bytes")
                self.store.remove_pdf(body["sha256"])
            return {"deleted": body["sha256"]}
        if path == "/api/example":
            body = object_fields(value, {"name"})
            groups = {
                "calibration": ["sensor-calibration.pdf"],
                "maintenance": ["pump-controller-guide.pdf", "maintenance-checklist.pdf"],
                "all": list(self.resources.examples),
            }
            if not isinstance(body["name"], str) or body["name"] not in groups:
                raise ValueError("Unknown prepared source set")
            example_files, sources = [], []
            for name in groups[body["name"]]:
                raw = self.resources.examples[name]
                digest = hashlib.sha256(raw).hexdigest()
                example_files.append(
                    {"name": name, "sha256": digest, "base64": base64.b64encode(raw).decode()}
                )
                sources.append(
                    {
                        "source_id": name.removesuffix(".pdf"),
                        "revision": "1.0",
                        "product_model": "Original synthetic reference manual",
                        "owner": "Synthetic documentation team",
                        "license": "MIT original synthetic fixture",
                        "path": "sources/" + digest + ".pdf",
                        "sha256": digest,
                        "migration_status": "in-review",
                    }
                )
            package = {
                "project_schema": 1,
                "product": self.resources.identity["product"],
                "input": {
                    "title": "Prepared " + body["name"] + " documentation",
                    "registry": {"registry_version": 1, "sources": sources},
                    "limits": {},
                },
                "files": example_files,
            }
            with self.data_lock:
                return self.store.import_project(package)
        raise KeyError("Unknown authored action")
