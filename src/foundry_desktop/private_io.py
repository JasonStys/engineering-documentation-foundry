from __future__ import annotations

import os
import stat
from pathlib import Path


def bounded(path: Path, limit: int) -> bytes:
    """Refuse links/devices/changed lengths and read only opened size plus one detection byte."""
    descriptor = os.open(
        path,
        os.O_RDONLY
        | getattr(os, "O_BINARY", 0)
        | getattr(os, "O_NONBLOCK", 0)
        | getattr(os, "O_NOFOLLOW", 0),
    )
    try:
        before = os.fstat(descriptor)
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_nlink != 1
            or not 0 <= before.st_size <= limit
        ):
            raise ValueError("Resource must be a bounded single-link ordinary file")
        remaining, blocks = min(before.st_size + 1, limit + 1), []
        while remaining:
            part = os.read(descriptor, min(remaining, 65536))
            if not part:
                break
            blocks.append(part)
            remaining -= len(part)
        after = os.fstat(descriptor)
        raw = b"".join(blocks)
        if len(raw) != before.st_size or after.st_size != before.st_size:
            raise ValueError("Resource changed while reading")
        return raw
    finally:
        os.close(descriptor)
