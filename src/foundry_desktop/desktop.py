class Window:
    """An ordinary native Open/Browser/Help/Exit window, independent of an IDE or command setup."""

    def __init__(self, resources: Resources, directory: Path, *, no_browser: bool = False) -> None:
        """Keep exit controls visible at the minimum size and user data unopened until Open
        is chosen.
        """
        self.resources, self.no_browser = resources, no_browser
        self.host: Host | None = None
        self.closer: threading.Thread | None = None
        self.results: queue.Queue[str | None] = queue.Queue()
        self.failed = False
        self.root = tk.Tk()
        self.root.title("Engineering Documentation Foundry | Jason Stys | " + __version__)
        self.root.geometry("730x440")
        self.root.minsize(650, 420)
        self.root.protocol("WM_DELETE_WINDOW", self.quit)
        shell = ttk.Frame(self.root, padding=22)
        shell.pack(fill="both", expand=True)
        actions = ttk.Frame(shell)
        actions.pack(side="bottom", fill="x", pady=(15, 0))
        self.exit_button = ttk.Button(actions, text="Exit", command=self.quit)
        self.exit_button.pack(side="right")
        ttk.Button(actions, text="Help", command=self.help).pack(side="left")
        self.browser_button = ttk.Button(
            actions, text="Open browser", command=self.browser, state="disabled"
        )
        self.browser_button.pack(side="left", padx=10)
        ttk.Label(
            shell,
            text="Author and review traceable documentation",
            font=("TkDefaultFont", 17, "bold"),
        ).pack(anchor="w")
        ttk.Label(
            shell, text="Jason Stys | local PDF source registry, publication and revision review"
        ).pack(anchor="w", pady=(8, 18))
        ttk.Label(shell, text="Workspace directory (one trusted OS owner)").pack(anchor="w")
        self.directory = tk.StringVar(value=str(directory))
        self.entry = ttk.Entry(shell, textvariable=self.directory)
        self.entry.pack(fill="x", pady=(6, 8))
        selection = ttk.Frame(shell)
        selection.pack(fill="x")
        self.choose_button = ttk.Button(selection, text="Choose folder", command=self.choose)
        self.choose_button.pack(side="left")
        self.open_button = ttk.Button(selection, text="Open workspace", command=self.open)
        self.open_button.pack(side="left", padx=10)
        self.status = tk.StringVar(
            value=(
                "Resources are verified. No workspace or document is open. Choose a "
                "directory, then Open workspace."
            )
        )
        self.status_label = ttk.Label(shell, textvariable=self.status, wraplength=590)
        self.status_label.pack(anchor="w", pady=(18, 0))

    def choose(self) -> None:
        """Choose a directory without creating, adopting or reading a workspace's contents."""
        selected = filedialog.askdirectory(
            parent=self.root, title="Choose an empty or existing Foundry workspace"
        )
        if selected:
            self.directory.set(selected)

    def open(self) -> None:
        """Open one admitted profile and prove actual listener readiness before enabling
        browser access.
        """
        if self.host is not None or self.closer is not None:
            return
        from foundry_desktop.server import Host

        candidate: Host | None = None
        try:
            candidate = Host(Path(self.directory.get()), self.resources)
            packet = candidate.ready()
            self.host = candidate
            self.failed = False
            self.entry.configure(state="disabled")
            self.choose_button.configure(state="disabled")
            self.open_button.configure(state="disabled")
            self.browser_button.configure(state="normal")
            self.status.set(
                "Owned workspace and actual browser application are ready. Closing the "
                "browser leaves this window running; use Exit when finished."
            )
            print(json.dumps({"event": "ready", **packet}), flush=True)
            if not self.no_browser:
                self.browser()
        except Exception as error:
            self.failed = True
            if candidate is not None:
                candidate.drain()
            self.status.set(
                "Workspace did not start: "
                + str(error)
                + " Choose a valid folder, or Exit. No existing workspace was reset."
            )

    def browser(self) -> None:
        """Open only this actual owned service; a browser failure never starts or adopts
        another listener.
        """
        if self.host is None or self.host.closing.is_set():
            return
        try:
            if not webbrowser.open(self.host.url + "/#native=" + self.host.token, new=1):
                self.status.set(
                    "The workspace is running, but the OS browser did not open. Try Open "
                    "browser or Exit normally."
                )
        except Exception as error:
            self.status.set("The workspace remains owned; browser opening failed: " + str(error))

    def help(self) -> None:
        """Explain the actual source/build/export workflow and local ownership boundaries."""
        messagebox.showinfo("Using Engineering Documentation Foundry", HELP, parent=self.root)

    def quit(self) -> None:
        """Repeated close requests retain ownership until actual accepted work and child
        processes finish.
        """
        if self.closer is not None:
            self.status.set(
                "Still closing the owned application. Wait for actual work to finish; "
                "no background service is being abandoned."
            )
            return
        if self.host is None:
            self.root.destroy()
            return
        self.host.request_close()
        self.browser_button.configure(state="disabled")
        self.open_button.configure(state="disabled")
        self.status.set(
            "Closing: waiting for accepted requests and actual PDF jobs. This "
            "window and workspace lock remain until the owner stops."
        )
        host = self.host

        def drain() -> None:
            """Join actual service work outside Tk's thread; only Tk's owner observes and
            destroys widgets.
            """
            try:
                host.drain()
                self.results.put(None)
            except Exception as error:
                self.results.put(str(error))

        self.closer = threading.Thread(target=drain, name="foundry-owned-drain")
        self.closer.start()
        self.root.after(40, self.poll)

    def poll(self) -> None:
        """Treat real completion as success; elapsed polls never release an active owner or
        fake exit zero.
        """
        if self.closer is None:
            return
        if self.closer.is_alive():
            self.root.after(40, self.poll)
            return
        self.closer.join()
        error = self.results.get_nowait()
        if error is None and self.host is not None and self.host.stopped.is_set():
            self.root.destroy()
        else:
            self.failed = True
            self.status.set(
                "The owner did not finish closing normally. Keep this workspace intact. "
                + str(error)
            )

    def watch(self) -> None:
        """Observe browser Quit through this same owner; no second drain thread can race the
        first.
        """
        if self.host is not None and self.host.closing.is_set() and self.closer is None:
            self.quit()
        self.root.after(40, self.watch)

    def run(self) -> int:
        """Run the genuine native menu until the user closes it and actual ownership is released."""
        self.root.after(40, self.watch)
        self.root.mainloop()
        return 1 if self.failed else 0


def main(arguments: list[str]) -> int:
    """Verify resources/setup first; normal launch requires an explicit native workspace choice."""
    parser = argparse.ArgumentParser(description="Engineering Documentation Foundry by Jason Stys")
    parser.add_argument(
        "--profile", type=Path, help="Explicit workspace directory; never an output path"
    )
    parser.add_argument("--no-window", action="store_true", help="Owned automation/console mode")
    parser.add_argument(
        "--no-browser", action="store_true", help="Do not invoke the OS browser opener"
    )
    parser.add_argument(
        "--setup-engine", action="store_true", help="Explicit console dependency consent only"
    )
    args = parser.parse_args(arguments)
    resources = load()
    if getattr(sys, "frozen", False):
        if not ensure(interactive=not args.no_window, console=args.setup_engine):
            return 0
        if args.setup_engine:
            return 0
        pin = parser_setup.selected_pin()
        resources = replace(
            resources,
            environment={
                **resources.environment,
                "FOUNDRY_DEPENDENCY_HOME": str(parser_setup.dependency_home()),
            },
            identity={
                **resources.identity,
                "pdf_engine": {
                    "version": parser_setup.VERSION,
                    "wheel_sha256": pin["sha256"],
                    "offline_verified": True,
                },
            },
        )
    else:
        if args.setup_engine:
            print(
                (
                    "Source mode uses its installed locked PDF environment; no native "
                    "dependency or workspace was changed."
                ),
                flush=True,
            )
            return 0
        resources = replace(
            resources,
            identity={
                **resources.identity,
                "pdf_engine": {
                    "version": importlib.import_module("pymupdf").__version__,
                    "source_environment": True,
                },
            },
        )
    directory = args.profile or default_directory()
    if not args.no_window:
        return Window(resources, directory, no_browser=args.no_browser).run()
    from foundry_desktop.server import Host

    host = Host(directory, resources)
    try:
        print(json.dumps({"event": "ready", **host.ready()}), flush=True)
        if not args.no_browser:
            webbrowser.open(host.url + "/#native=" + host.token, new=1)
        try:
            host.closing.wait()
        except KeyboardInterrupt:
            host.request_close()
    finally:
        host.drain()
    print(
        json.dumps({"event": "stopped", "nonce": host.nonce, "normal": host.stopped.is_set()}),
        flush=True,
    )
    return 0 if host.stopped.is_set() else 1
