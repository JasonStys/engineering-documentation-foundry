def equal(value: str | None, expected: str) -> bool:
    """Non-ASCII or absent credentials fail normally instead of raising from compare_digest."""
    return value is not None and value.isascii() and hmac.compare_digest(value, expected)


class LimitedServer(ThreadingHTTPServer):
    """Bound accepted worker threads; closing joins actual handlers rather than abandoning
    daemon work.
    """

    daemon_threads = False
    block_on_close = True
    allow_reuse_address = False

    def __init__(self, handler: type[BaseHTTPRequestHandler]):
        """Reserve a fresh loopback-only port; no configured endpoint or existing service is
        adopted.
        """
        self.slots = threading.BoundedSemaphore(4)
        super().__init__(("127.0.0.1", 0), handler)

    def process_request(self, request: Any, client_address: Any) -> None:
        """Refuse excess transport work before spawning more threads or reading uploaded bodies."""
        if not self.slots.acquire(blocking=False):
            try:
                request.sendall(
                    b"HTTP/1.1 503 Service Unavailable\r\nContent-Length: 0\r\n"
                    b"Connection: close\r\n\r\n"
                )
            finally:
                self.shutdown_request(request)
            return
        started = False
        try:
            super().process_request(request, client_address)
            started = True
        finally:
            if not started:
                self.slots.release()

    def process_request_thread(self, request: Any, client_address: Any) -> None:
        """Release only this actual handler's admission slot, including exceptional
        connection exits.
        """
        try:
            super().process_request_thread(request, client_address)
        finally:
            self.slots.release()


class Host:
    """Own resources, admitted workspace, listener and complete graceful-stop lifecycle together."""

    def __init__(self, directory: Path, resources: Resources):
        """Acquire one profile then construct a fixed local service; failures retain no false
        running state.
        """
        self.resources = resources
        self.profile = Profile(directory)
        self.token, self.nonce = secrets.token_urlsafe(32), secrets.token_hex(16)
        self.closing, self.stopped = threading.Event(), threading.Event()
        self.drain_lock = threading.Lock()
        self.error: str | None = None
        accepted = False
        listener: LimitedServer | None = None
        try:
            self.service = Service(self.profile, resources)
            self.server = LimitedServer(self._handler())
            listener = self.server
            self.authority = "127.0.0.1:" + str(self.server.server_port)
            self.url = "http://" + self.authority
            self.cookie = "edf_preview_" + self.nonce
            self.thread = threading.Thread(
                target=self.server.serve_forever,
                kwargs={"poll_interval": 0.05},
                name="foundry-owned-listener",
            )
            self.thread.start()
            accepted = True
        finally:
            if not accepted:
                if listener is not None:
                    listener.server_close()
                self.profile.close()

    def ready(self) -> dict[str, Any]:
        """Verify an actual owned HTTP response and nonce before claiming successful
        application readiness.
        """
        import http.client

        connection = http.client.HTTPConnection("127.0.0.1", self.server.server_port, timeout=5)
        try:
            connection.request("GET", "/health")
            response = connection.getresponse()
            value = json.loads(response.read(16385))
            if (
                response.status != 200
                or value.get("nonce") != self.nonce
                or value.get("identity") != self.resources.identity
            ):
                raise ValueError("Owned listener readiness did not match this application")
        finally:
            connection.close()
        return {
            "url": self.url,
            "nonce": self.nonce,
            "token": self.token,
            "identity": self.resources.identity,
        }

    def request_close(self) -> None:
        """Stop admitting authored work; the owner stays open until the actual
        listener/handlers stop.
        """
        self.closing.set()

    def drain(self) -> None:
        """Join the real accept loop and handlers before releasing the exact workspace lock."""
        with self.drain_lock:
            if self.stopped.is_set():
                return
            self.request_close()
            try:
                self.server.shutdown()
                self.thread.join()
                self.server.server_close()
            except Exception as error:
                self.error = str(error)
                raise
            finally:
                # server_close joins all non-daemon request threads before returning.
                if not self.thread.is_alive() and self.error is None:
                    self.profile.close()
                    self.stopped.set()

    def _handler(self) -> type[BaseHTTPRequestHandler]:
        """Close over only this owner's state; browser fields cannot select another
        instance/profile.
        """
        owner = self

        class Handler(BaseHTTPRequestHandler):
            """A fixed JSON/static protocol with no filesystem router, CORS permission or
            setup endpoint.
            """

            protocol_version = "HTTP/1.1"

            def setup(self) -> None:
                """Bound idle/framing transport work; actual engine execution has its own
                finite deadline.
                """
                self.request.settimeout(5)
                super().setup()

            def log_message(self, format: str, *args: Any) -> None:
                """Keep local source/document identifiers and request metadata out of ambient
                console logs.
                """

            def one(self, name: str) -> str | None:
                """Reject ambiguous duplicate authority/credential headers before reading any
                body.
                """
                values = self.headers.get_all(name) or []
                if len(values) > 1:
                    raise PermissionError("Duplicate authority/credential header")
                return values[0] if values else None

            def allowed(self, *, mutation: bool = False, preview: bool = False) -> None:
                """Require exact loopback authority and capability; preview cookie has no
                mutation authority.
                """
                if self.one("Host") != owner.authority:
                    raise PermissionError("Unexpected application authority")
                origin = self.one("Origin")
                if (origin is not None and origin != owner.url) or (
                    mutation and origin != owner.url
                ):
                    raise PermissionError("Unexpected application origin")
                if preview:
                    if self.one("Sec-Fetch-Site") not in (None, "same-origin"):
                        raise PermissionError("Preview requires its own application frame")
                    cookies = SimpleCookie()
                    try:
                        cookies.load(self.one("Cookie") or "")
                    except CookieError as error:
                        raise PermissionError("Invalid preview session cookie") from error
                    value = cookies.get(owner.cookie)
                    if value is None or not equal(value.value, owner.token):
                        raise PermissionError("Open preview from the owned application")
                elif not equal(self.one("X-Foundry-Capability"), owner.token):
                    raise PermissionError("Application capability is required")

            def respond(
                self,
                status: int,
                raw: bytes,
                media: str = "application/json; charset=utf-8",
                *,
                preview: bool = False,
                filename: str | None = None,
                cookie: str | None = None,
            ) -> None:
                """Return explicit bounded bytes with no cache, external script, popup
                permission or MIME guessing.
                """
                self.close_connection = True
                self.send_response(status)
                for name, value in {
                    "Content-Type": media,
                    "Content-Length": str(len(raw)),
                    "Cache-Control": "no-store",
                    "Connection": "close",
                    "X-Content-Type-Options": "nosniff",
                    "Referrer-Policy": "no-referrer",
                    "Content-Security-Policy": PREVIEW_CSP if preview else APP_CSP,
                    "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
                }.items():
                    self.send_header(name, value)
                if filename is not None:
                    self.send_header(
                        "Content-Disposition", 'attachment; filename="' + filename + '"'
                    )
                if cookie is not None:
                    self.send_header("Set-Cookie", cookie)
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(raw)

            def failure(self, status: int, error: Exception) -> None:
                """Describe the failed action without changing saved data or inventing a
                successful outcome.
                """
                try:
                    self.respond(status, canonical({"error": " ".join(str(error).split())[:1000]}))
                except (ConnectionError, TimeoutError):
                    self.close_connection = True

            def do_GET(self) -> None:
                """Serve fixed application resources, exact saved data or sandboxed original
                publication bytes.
                """
                try:
                    if self.one("Host") != owner.authority:
                        raise PermissionError("Unexpected application authority")
                    target = urlsplit(self.path)
                    if (
                        target.scheme
                        or target.netloc
                        or self.headers.get_all("Transfer-Encoding")
                        or self.headers.get_all("Content-Length")
                    ):
                        raise ValueError("Unsupported read request framing")
                    path = unquote(target.path)
                    values = parse_qs(target.query, keep_blank_values=True, strict_parsing=True)
                    if any(len(items) != 1 for items in values.values()):
                        raise ValueError("Duplicate query fields")
                    query = {key: items[0] for key, items in values.items()}
                    if path in owner.resources.assets and not query:
                        media, raw = owner.resources.assets[path]
                        self.respond(200, raw, media)
                        return
                    if path == "/health" and not query:
                        self.respond(
                            200,
                            canonical({"nonce": owner.nonce, "identity": owner.resources.identity}),
                        )
                        return
                    if path.startswith("/preview/"):
                        self.allowed(preview=True)
                        _, _, identifier, logical = path.split("/", 3)
                        _, files = owner.service.publication(identifier)
                        if query or logical not in files or not logical.endswith((".html", ".css")):
                            raise KeyError("Preview artifact not found")
                        self.respond(
                            200,
                            files[logical],
                            "text/css; charset=utf-8"
                            if logical.endswith(".css")
                            else "text/html; charset=utf-8",
                            preview=True,
                        )
                        return
                    self.allowed()
                    if path == "/api/library" and not query:
                        result: Any = owner.service.store.library()
                    elif path == "/api/source" and set(query) == {"sha256"}:
                        raw = owner.service.store.source(query["sha256"])
                        self.respond(
                            200,
                            raw,
                            "application/pdf",
                            filename="foundry-source-" + query["sha256"] + ".pdf",
                        )
                        return
                    elif path == "/api/projects" and set(query) <= {"q"}:
                        result = owner.service.store.listing("projects", query.get("q", ""))
                    elif path == "/api/builds" and set(query) <= {"q", "status"}:
                        result = owner.service.store.listing(
                            "builds", query.get("q", ""), query.get("status", "")
                        )
                    elif path == "/api/project" and set(query) == {"id"}:
                        result = owner.service.store.project(query["id"])
                    elif (
                        path == "/api/detail"
                        and "id" in query
                        and set(query) <= {"id", "q", "kind", "source"}
                    ):
                        result = owner.service.detail(
                            query["id"],
                            query.get("q", ""),
                            query.get("kind", ""),
                            query.get("source", ""),
                        )
                    elif path == "/api/export-project" and set(query) == {"id", "revision"}:
                        result = owner.service.store.export_project(
                            query["id"], int(query["revision"])
                        )
                        self.respond(
                            200,
                            canonical(result),
                            filename="foundry-project-" + query["id"] + ".json",
                        )
                        return
                    elif path == "/api/export-build" and set(query) == {"id", "kind"}:
                        record = owner.service.store.build(query["id"], with_bundle=True)
                        archive = record.pop("bundle")
                        if query["kind"] == "zip":
                            self.respond(
                                200,
                                archive,
                                "application/zip",
                                filename="foundry-artifacts-" + record["id"] + ".zip",
                            )
                        elif query["kind"] == "evidence":
                            self.respond(
                                200,
                                canonical(record),
                                filename="foundry-build-" + record["id"] + ".json",
                            )
                        else:
                            raise ValueError("Unsupported build export")
                        return
                    elif path == "/api/artifact" and set(query) == {"id", "path"}:
                        _, files = owner.service.publication(query["id"])
                        if query["path"] not in files:
                            raise KeyError("Original artifact not found")
                        self.respond(
                            200,
                            files[query["path"]],
                            "application/octet-stream",
                            filename="foundry-" + query["path"].rsplit("/", 1)[-1],
                        )
                        return
                    else:
                        raise KeyError("Application resource not found")
                    self.respond(200, canonical(result))
                except PermissionError as error:
                    self.failure(403, error)
                except Conflict as error:
                    self.failure(409, error)
                except KeyError as error:
                    self.failure(404, error)
                except (ValueError, TypeError) as error:
                    self.failure(400, error)
                except OSError as error:
                    self.failure(500, error)
                except sqlite3.Error as error:
                    self.failure(507, error)

            def do_POST(self) -> None:
                """Authorize before reading input; no remote origin or unknown endpoint
                provisions an owner.
                """
                try:
                    self.allowed(mutation=True)
                    if owner.closing.is_set():
                        raise Conflict("The owner is closing; no new operation was started")
                    target = urlsplit(self.path)
                    if target.query or target.fragment or target.scheme or target.netloc:
                        raise ValueError("Authored actions do not accept URL parameters")
                    length = self.one("Content-Length")
                    if (
                        self.headers.get_all("Transfer-Encoding")
                        or self.one("Content-Type") != "application/json"
                        or length is None
                        or not length.isascii()
                        or not length.isdigit()
                        or not 1 <= int(length) <= MAX_REQUEST
                    ):
                        raise ValueError("Use one bounded application/json Content-Length request")
                    expectation = self.one("Expect")
                    if expectation is not None:
                        if expectation.casefold() != "100-continue":
                            raise ValueError("Unsupported request expectation")
                        # Standard admission handshake follows authorization and framing.
                        self.send_response_only(100)
                        self.end_headers()
                    raw = self.rfile.read(int(length))
                    if len(raw) != int(length):
                        raise ValueError("Incomplete JSON request body")
                    value = parsed(raw)
                    if target.path == "/api/quit":
                        body = object_fields(value, {"confirm"})
                        if body["confirm"] is not True:
                            raise ValueError("Explicit Quit confirmation is required")
                        owner.request_close()
                        self.respond(
                            200,
                            canonical({"close_requested": True, "owned_work_must_finish": True}),
                            cookie=owner.cookie
                            + "=; Path=/preview/; HttpOnly; SameSite=Strict; Max-Age=0",
                        )
                    elif target.path == "/api/preview-session":
                        body = object_fields(value, {"purpose"})
                        if body["purpose"] != "preview":
                            raise ValueError("Unknown preview-session purpose")
                        self.respond(
                            200,
                            canonical({"ready": True}),
                            cookie=owner.cookie
                            + "="
                            + owner.token
                            + "; Path=/preview/; HttpOnly; SameSite=Strict; Max-Age=1800",
                        )
                    else:
                        result = owner.service.action(target.path, value)
                        status = (
                            201
                            if target.path
                            in {"/api/save", "/api/import", "/api/build", "/api/example"}
                            else 200
                        )
                        if target.path == "/api/upload" and result["created"]:
                            status = 201
                        self.respond(status, canonical(result))
                except PermissionError as error:
                    self.failure(403, error)
                except Conflict as error:
                    self.failure(409, error)
                except KeyError as error:
                    self.failure(404, error)
                except (ValueError, TypeError) as error:
                    self.failure(400, error)
                except OSError as error:
                    self.failure(500, error)
                except sqlite3.Error as error:
                    self.failure(507, error)

            def unsupported(self) -> None:
                """Reject extra HTTP verbs and preflights without granting CORS or mutation
                authority.
                """
                self.failure(
                    405, ValueError("Only the owned GET/POST application protocol is supported")
                )

            def handle_expect_100(self) -> bool:
                """Defer body permission until the application authenticates and admits the
                request.
                """
                return True

            do_PUT = unsupported
            do_PATCH = unsupported
            do_DELETE = unsupported
            do_OPTIONS = unsupported
            do_HEAD = unsupported

        return Handler
