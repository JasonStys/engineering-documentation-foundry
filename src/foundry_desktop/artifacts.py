def logical(name: str) -> None:
    """Allow only conventional relative original artifact names, excluding URL/Windows aliases."""
    if (
        not name
        or len(name) > 300
        or any(char in name for char in "\\:")
        or name.startswith("/")
        or any(part in {"", ".", ".."} for part in name.split("/"))
        or any(ord(char) < 32 for char in name)
    ):
        raise ValueError("Invalid publication artifact path")
    if PurePosixPath(name).suffix not in {".json", ".jsonl", ".html", ".css", ".txt", ".md"}:
        raise ValueError("Unsupported publication artifact type")


def checked_files(files: dict[str, bytes]) -> JSON:
    """Verify the complete original manifest and publication decision against actual retained
    bytes.

    """
    if not files or len(files) > 2048 or sum(map(len, files.values())) > MAX_OUTPUT:
        raise ValueError("Publication artifacts exceed their file/byte bound")
    for name in files:
        logical(name)
    if "build-manifest.json" not in files:
        raise ValueError("Original build manifest is absent")
    manifest: Any = json.loads(files["build-manifest.json"])
    if (
        not isinstance(manifest, dict)
        or set(manifest) != {"manifest_version", "files"}
        or type(manifest["manifest_version"]) is not int
        or manifest["manifest_version"] != 1
        or not isinstance(manifest["files"], list)
    ):
        raise ValueError("Unknown original artifact manifest")
    seen = set()
    for row in manifest["files"]:
        if (
            not isinstance(row, dict)
            or set(row) != {"path", "sha256", "bytes"}
            or not isinstance(row["path"], str)
        ):
            raise ValueError("Invalid artifact manifest row")
        name = row["path"]
        if name in seen or name not in files or name == "build-manifest.json":
            raise ValueError("Duplicate or absent artifact identity")
        seen.add(name)
        if (
            type(row["bytes"]) is not int
            or row["bytes"] != len(files[name])
            or row["sha256"] != hashlib.sha256(files[name]).hexdigest()
        ):
            raise ValueError("Actual publication bytes differ from original manifest")
    if seen != set(files) - {"build-manifest.json"}:
        raise ValueError("Original publication manifest is incomplete")
    report: JSON = json.loads(files["reports/migration-report.json"])
    if report.get("publication_allowed") is True:
        if "site/index.html" not in files or "PUBLICATION_BLOCKED.txt" in files:
            raise ValueError("Published report has inconsistent output")
    elif report.get("publication_allowed") is False:
        if "PUBLICATION_BLOCKED.txt" not in files or any(
            name.startswith("site/") for name in files
        ):
            raise ValueError("Blocked report cannot supply a published HTML site")
    else:
        raise ValueError("Original publication decision is absent")
    return report


def pack(directory: Path) -> tuple[JSON, bytes]:
    """Read fresh child output with early traversal and actual descriptor byte bounds."""
    root_info = directory.lstat()
    if not stat.S_ISDIR(root_info.st_mode) or directory.resolve() != directory:
        raise ValueError("Generated output root is not an owned directory")
    files: dict[str, bytes] = {}
    pending, visited, total = [directory], 0, 0
    while pending:
        parent = pending.pop()
        for path in parent.iterdir():
            visited += 1
            if visited > 4096:
                raise ValueError("Generated output traversal exceeded its bound")
            info = path.lstat()
            if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & getattr(
                stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0
            ):
                raise ValueError("Linked generated output refused")
            if stat.S_ISDIR(info.st_mode):
                pending.append(path)
            elif stat.S_ISREG(info.st_mode):
                name = path.relative_to(directory).as_posix()
                logical(name)
                raw = bounded(path, min(MAX_OUTPUT - total, 16 * 1024 * 1024))
                files[name] = raw
                total += len(raw)
                if len(files) > 2048:
                    raise ValueError("Generated file count exceeds its bound")
            else:
                raise ValueError("Generated output is not an ordinary file/directory")
    report = checked_files(files)
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, raw in sorted(files.items()):
            zip_info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
            zip_info.compress_type = zipfile.ZIP_DEFLATED
            zip_info.external_attr = (stat.S_IFREG | 0o644) << 16
            archive.writestr(zip_info, raw)
    return report, output.getvalue()


def unpack(raw: bytes) -> dict[str, bytes]:
    """Reverify stored ZIP evidence without extracting a path or trusting declared expansion."""
    if len(raw) > MAX_OUTPUT:
        raise ValueError("Stored publication archive exceeds its bound")
    files: dict[str, bytes] = {}
    total = 0
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        entries = archive.infolist()
        if not 1 <= len(entries) <= 2048:
            raise ValueError("Stored publication count exceeds its bound")
        for entry in entries:
            name = entry.orig_filename
            logical(name)
            if (
                name != entry.filename
                or name in files
                or entry.is_dir()
                or entry.flag_bits & 1
                or entry.compress_type not in {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}
            ):
                raise ValueError("Unsupported/ambiguous stored artifact")
            with archive.open(entry) as stream:
                data = stream.read(min(16 * 1024 * 1024, MAX_OUTPUT - total) + 1)
            total += len(data)
            if len(data) != entry.file_size or len(data) > 16 * 1024 * 1024 or total > MAX_OUTPUT:
                raise ValueError("Actual stored expansion exceeds its bound")
            files[name] = data
    checked_files(files)
    return files


def input_sha(value: JSON) -> str:
    """Bind the authored registry/options independently from original source/artifact digests."""
    return hashlib.sha256(canonical(value)).hexdigest()
