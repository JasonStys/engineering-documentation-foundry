from __future__ import annotations

import base64
import hashlib
import json
import sqlite3
import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from foundry_desktop.contract import (
    JSON,
    MAX_SOURCE_BYTES,
    PRODUCT,
    ProjectInput,
    canonical,
    object_fields,
    opaque,
    pdf_upload,
    project_input,
)
from foundry_desktop.profile_paths import workspace_members

MAX_HISTORY = 256 * 1024 * 1024


def timestamp() -> str:
    """Keep mutable local history time separate from deterministic original-engine artifacts."""
    return datetime.now(UTC).isoformat()


class Conflict(ValueError):
    """An edited/selected project changed; it must be reviewed instead of overwritten."""


class Store:
    """Short per-thread SQLite connections, explicit schema and bounded retained byte inventory."""

    def __init__(self, path: Path):
        """Refuse future schemas and initialize only the application's already admitted path."""
        self.path = path
        with self.connect() as database:
            if database.execute("PRAGMA user_version").fetchone()[0] not in (0, 1):
                raise ValueError("Unsupported future workspace schema; no migration attempted")
            database.execute(
                "CREATE TABLE IF NOT EXISTS pdfs (sha TEXT PRIMARY KEY,name TEXT NOT "
                "NULL,data BLOB NOT NULL)"
            )
            database.execute(
                "CREATE TABLE IF NOT EXISTS projects (id TEXT PRIMARY KEY,title TEXT "
                "NOT NULL,revision INTEGER NOT NULL,updated TEXT NOT NULL,input TEXT "
                "NOT NULL)"
            )
            database.execute(
                "CREATE TABLE IF NOT EXISTS builds (id TEXT PRIMARY KEY,project TEXT "
                "NOT NULL,revision INTEGER NOT NULL,title TEXT NOT NULL,created TEXT "
                "NOT NULL,status TEXT NOT NULL,input TEXT NOT NULL,report TEXT NOT "
                "NULL,bundle BLOB NOT NULL,sha TEXT NOT NULL,engine TEXT NOT NULL)"
            )
            database.execute("PRAGMA user_version=1")

    @contextmanager
    def connect(self) -> Iterator[sqlite3.Connection]:
        """Recheck fixed recovery members; commit atomically or roll back and close on every
        exit.

        """
        workspace_members(self.path.parent)
        database = sqlite3.connect(self.path, timeout=5)
        database.row_factory = sqlite3.Row
        try:
            with database:
                yield database
        finally:
            database.close()

    def budget(self, database: sqlite3.Connection, extra: int) -> None:
        """Reject explicit capacity exhaustion instead of pruning evidence or silently
        truncating.

        """
        size = sum(
            database.execute(query).fetchone()[0]
            for query in (
                "SELECT COALESCE(SUM(LENGTH(data)),0) FROM pdfs",
                (
                    "SELECT "
                    "COALESCE(SUM(LENGTH(bundle)+LENGTH(report)+LENGTH(input)+LENGTH(engine)),0)"
                    " FROM builds"
                ),
                "SELECT COALESCE(SUM(LENGTH(input)),0) FROM projects",
            )
        )
        if size + extra > MAX_HISTORY:
            raise ValueError(
                "Workspace holds 256 MiB; export and explicitly remove unused records first"
            )

    def upload(self, name: str, raw: bytes) -> JSON:
        """Deduplicate exact uploaded PDF bytes without replacing an earlier display name."""
        digest = hashlib.sha256(raw).hexdigest()
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            existing = database.execute("SELECT name FROM pdfs WHERE sha=?", (digest,)).fetchone()
            if existing is None:
                if database.execute("SELECT COUNT(*) FROM pdfs").fetchone()[0] >= 120:
                    raise ValueError("Library holds 120 PDFs; explicitly remove unused sources")
                self.budget(database, len(raw))
                database.execute("INSERT INTO pdfs VALUES (?,?,?)", (digest, name, raw))
            else:
                name = existing["name"]
        return {
            "sha256": digest,
            "created": existing is None,
            "name": name,
            "bytes": len(raw),
            "path": "sources/" + digest + ".pdf",
        }

    def library(self) -> list[JSON]:
        """List source identities and sizes without returning every PDF's bytes."""
        with self.connect() as database:
            return [
                dict(row)
                for row in database.execute(
                    "SELECT sha AS sha256,name,LENGTH(data) AS bytes FROM pdfs ORDER BY name,sha"
                )
            ]

    def files(self, project: ProjectInput) -> dict[str, bytes]:
        """Resolve only saved hash identities and independently rehash actual retained bytes."""
        with self.connect() as database:
            return self._files(database, project)

    def source(self, digest: str) -> bytes:
        """Return exact selected uploaded bytes only after rechecking their content identity."""
        if len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
            raise ValueError("Invalid source PDF identity")
        with self.connect() as database:
            row = database.execute("SELECT data FROM pdfs WHERE sha=?", (digest,)).fetchone()
            if row is None:
                raise KeyError("Source PDF not found")
            raw = bytes(row["data"])
            if hashlib.sha256(raw).hexdigest() != digest:
                raise ValueError("Retained source PDF identity differs")
            return raw

    def _files(self, database: sqlite3.Connection, project: ProjectInput) -> dict[str, bytes]:
        """Validate source references within the same transaction as a save/export decision."""
        result: dict[str, bytes] = {}
        for digest in sorted(project.hashes()):
            row = database.execute("SELECT data FROM pdfs WHERE sha=?", (digest,)).fetchone()
            if row is None:
                raise ValueError("An authored source PDF is not in this workspace library")
            raw = bytes(row["data"])
            if hashlib.sha256(raw).hexdigest() != digest:
                raise ValueError("Saved PDF integrity mismatch")
            result[digest] = raw
        if sum(map(len, result.values())) > MAX_SOURCE_BYTES:
            raise ValueError("A project supports at most 32 MiB of unique PDF bytes")
        return result

    def save(self, value: Any, identifier: Any, expected: Any) -> JSON:
        """Create or optimistically revise an authored project, preserving prior immutable
        builds.

        """
        project = project_input(value)
        raw = canonical(project.model_dump(mode="json")).decode()
        if type(expected) is not int or expected < 0:
            raise ValueError("Expected project revision must be an integer")
        if identifier is not None:
            identifier = opaque(identifier)
        elif expected != 0:
            raise Conflict("A new project starts at revision 0")
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            self._files(database, project)
            self.budget(database, len(raw))
            updated = timestamp()
            if identifier is None:
                if database.execute("SELECT COUNT(*) FROM projects").fetchone()[0] >= 30:
                    raise ValueError(
                        "Workspace holds 30 projects; export/remove selected old projects"
                    )
                identifier = uuid.uuid4().hex
                revision = 1
                database.execute(
                    "INSERT INTO projects VALUES (?,?,?,?,?)",
                    (identifier, project.title, revision, updated, raw),
                )
            else:
                revision = expected + 1
                changed = database.execute(
                    (
                        "UPDATE projects SET title=?,revision=?,updated=?,input=? WHERE id=? "
                        "AND revision=?"
                    ),
                    (project.title, revision, updated, raw, identifier, expected),
                )
                if changed.rowcount != 1:
                    raise Conflict(
                        "Project changed or was removed; reload its current saved revision"
                    )
        return {
            "id": identifier,
            "title": project.title,
            "revision": revision,
            "updated": updated,
            "input": project.model_dump(mode="json"),
        }

    def export_project(self, identifier: Any, expected: Any) -> JSON:
        """Capture one exact saved revision plus all actual source bytes in a consistent read
        transaction.

        """
        identifier = opaque(identifier)
        with self.connect() as database:
            database.execute("BEGIN")
            row = database.execute(
                "SELECT revision,input FROM projects WHERE id=?", (identifier,)
            ).fetchone()
            if row is None:
                raise KeyError("Saved project not found")
            if type(expected) is not int or row["revision"] != expected:
                raise Conflict("Project changed; reload before exporting the saved snapshot")
            project = ProjectInput.model_validate_json(row["input"])
            files = self._files(database, project)
            names = {
                item["sha256"]: item["name"]
                for item in database.execute("SELECT sha AS sha256,name FROM pdfs")
            }
        return {
            "project_schema": 1,
            "product": PRODUCT,
            "input": project.model_dump(mode="json"),
            "files": [
                {
                    "sha256": digest,
                    "name": names[digest],
                    "base64": base64.b64encode(raw).decode(),
                }
                for digest, raw in sorted(files.items())
            ],
        }

    def import_project(self, value: Any) -> JSON:
        """Validate all bytes first; atomically import as a new project without adopting
        exported IDs/results.

        """
        value = object_fields(value, {"project_schema", "product", "input", "files"})
        if (
            type(value["project_schema"]) is not int
            or value["project_schema"] != 1
            or value["product"] != PRODUCT
        ):
            raise ValueError("Unsupported portable project identity")
        project = ProjectInput.model_validate(value["input"])
        if not isinstance(value["files"], list) or not 1 <= len(value["files"]) <= 12:
            raise ValueError("A portable project requires its complete bounded PDF inventory")
        files: dict[str, tuple[str, bytes]] = {}
        for item in value["files"]:
            item = object_fields(item, {"sha256", "name", "base64"})
            name, raw, digest = pdf_upload(item["name"], item["base64"])
            if digest != item["sha256"] or digest in files:
                raise ValueError("Duplicate or incorrect portable PDF identity")
            files[digest] = name, raw
        if (
            set(files) != project.hashes()
            or sum(len(raw) for _, raw in files.values()) > MAX_SOURCE_BYTES
        ):
            raise ValueError("Portable PDF inventory differs from the authored project")
        identifier, updated = uuid.uuid4().hex, timestamp()
        encoded = canonical(project.model_dump(mode="json")).decode()
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            if database.execute("SELECT COUNT(*) FROM projects").fetchone()[0] >= 30:
                raise ValueError("Workspace holds 30 projects; export/remove selected old projects")
            additions = []
            for digest, (name, raw) in files.items():
                row = database.execute("SELECT data FROM pdfs WHERE sha=?", (digest,)).fetchone()
                if row is None:
                    additions.append((digest, name, raw))
                elif hashlib.sha256(row["data"]).hexdigest() != digest:
                    raise ValueError("Existing source integrity mismatch; no import was written")
            if database.execute("SELECT COUNT(*) FROM pdfs").fetchone()[0] + len(additions) > 120:
                raise ValueError("Source library would exceed 120 PDFs")
            self.budget(database, len(encoded) + sum(len(raw) for _, _, raw in additions))
            database.executemany("INSERT INTO pdfs VALUES (?,?,?)", additions)
            database.execute(
                "INSERT INTO projects VALUES (?,?,?,?,?)",
                (identifier, project.title, 1, updated, encoded),
            )
        return {
            "id": identifier,
            "title": project.title,
            "revision": 1,
            "updated": updated,
            "input": project.model_dump(mode="json"),
        }

    def remove_project(self, identifier: Any, expected: Any) -> None:
        """Remove only an explicitly selected current draft; immutable builds and PDFs remain."""
        identifier = opaque(identifier)
        if type(expected) is not int:
            raise ValueError("Project revision must be an integer")
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            if (
                database.execute(
                    "DELETE FROM projects WHERE id=? AND revision=?", (identifier, expected)
                ).rowcount
                != 1
            ):
                raise Conflict("Project changed or was removed; review the current selection")

    def remove_build(self, identifier: Any) -> None:
        """Delete exactly one selected build; never cascade to other evidence or source files."""
        with self.connect() as database:
            if (
                database.execute("DELETE FROM builds WHERE id=?", (opaque(identifier),)).rowcount
                != 1
            ):
                raise KeyError("Saved build not found")

    def remove_pdf(self, digest: str) -> None:
        """Refuse deletion of a PDF referenced by any saved project or immutable build."""
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            for table in ("projects", "builds"):
                for row in database.execute("SELECT input FROM " + table):
                    if digest in ProjectInput.model_validate_json(row["input"]).hashes():
                        raise Conflict(
                            "This PDF is referenced by a saved project/build; export and remove "
                            "that record first"
                        )
            if database.execute("DELETE FROM pdfs WHERE sha=?", (digest,)).rowcount != 1:
                raise KeyError("Source PDF not found")

    def project(self, identifier: Any, expected: Any = None) -> JSON:
        """Read an exact selected revision or refuse stale builds rather than silently
        switching inputs.

        """
        identifier = opaque(identifier)
        with self.connect() as database:
            row = database.execute("SELECT * FROM projects WHERE id=?", (identifier,)).fetchone()
        if row is None:
            raise KeyError("Saved project not found")
        if expected is not None and (type(expected) is not int or row["revision"] != expected):
            raise Conflict("Saved revision changed; review and choose Build again")
        result = dict(row)
        result["input"] = json.loads(row["input"])
        return result

    def listing(self, kind: str, query: str = "", status: str = "") -> list[JSON]:
        """Search literal titles in bounded stable history; statuses never select an SQL
        expression.

        """
        if (
            not isinstance(query, str)
            or len(query) > 100
            or status not in ("", "published", "blocked")
        ):
            raise ValueError("Unsupported history filter")
        literal = query.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        with self.connect() as database:
            if kind == "projects":
                rows = database.execute(
                    (
                        "SELECT id,title,revision,updated FROM projects WHERE title LIKE ? "
                        "ESCAPE '\\' ORDER BY updated DESC,id DESC"
                    ),
                    ("%" + literal + "%",),
                )
            elif kind == "builds":
                rows = database.execute(
                    (
                        "SELECT id,project,revision,title,created,status,sha FROM builds WHERE "
                        "title LIKE ? ESCAPE '\\' AND (?='' OR status=?) ORDER BY created "
                        "DESC,id DESC"
                    ),
                    ("%" + literal + "%", status, status),
                )
            else:
                raise ValueError("Unknown history kind")
            return [dict(row) for row in rows]

    def retain_build(self, project: JSON, report: JSON, bundle: bytes, engine: JSON) -> JSON:
        """Persist only a completed original engine outcome and its exact artifact archive
        atomically.

        """
        identifier = uuid.uuid4().hex
        status = "published" if report["publication_allowed"] else "blocked"
        input_json, report_json = canonical(project["input"]).decode(), canonical(report).decode()
        with self.connect() as database:
            database.execute("BEGIN IMMEDIATE")
            if database.execute("SELECT COUNT(*) FROM builds").fetchone()[0] >= 50:
                raise ValueError(
                    "Workspace holds 50 builds; export and explicitly remove selected evidence"
                )
            self.budget(
                database, len(bundle) + len(input_json) + len(report_json) + len(canonical(engine))
            )
            database.execute(
                "INSERT INTO builds VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                (
                    identifier,
                    project["id"],
                    project["revision"],
                    project["title"],
                    timestamp(),
                    status,
                    input_json,
                    report_json,
                    bundle,
                    hashlib.sha256(bundle).hexdigest(),
                    canonical(engine).decode(),
                ),
            )
        return self.build(identifier)

    def build(self, identifier: Any, *, with_bundle: bool = False) -> JSON:
        """Retrieve exact historical evidence; no current project revision rewrites a past build."""
        identifier = opaque(identifier)
        with self.connect() as database:
            row = database.execute("SELECT * FROM builds WHERE id=?", (identifier,)).fetchone()
        if row is None:
            raise KeyError("Saved build not found")
        result = dict(row)
        raw = bytes(result.pop("bundle"))
        if hashlib.sha256(raw).hexdigest() != result["sha"]:
            raise ValueError("Saved build artifact integrity mismatch")
        result["input"], result["report"] = (
            json.loads(result["input"]),
            json.loads(result["report"]),
        )
        result["engine"] = json.loads(result["engine"])
        if with_bundle:
            result["bundle"] = raw
        return result
