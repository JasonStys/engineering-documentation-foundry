def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    """Reject duplicate JSON keys instead of silently accepting an ambiguous last value."""
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON object key: {key}")
        result[key] = value
    return result


def load_topics(path: Path) -> tuple[Topic, ...]:
    """Read at most 16 MiB and 10,000 strict canonical topics from an explicitly selected file.

    Args:
        path: A canonical topics.json selected by the reviewer, including blocked-build data.
    Returns:
        Validated immutable topics; an empty corpus is valid for complete removals.
    Raises:
        ValueError: Oversize, malformed, duplicated or schema-invalid corpus.
    """
    with path.open("rb") as source:
        content = source.read(MAX_CORPUS_BYTES + 1)
    if len(content) > MAX_CORPUS_BYTES:
        raise ValueError("canonical corpus exceeds the 16 MiB comparison limit")
    try:
        payload = json.loads(content.decode("utf-8"), object_pairs_hook=_unique_object)
    except (UnicodeError, RecursionError) as error:
        raise ValueError("canonical corpus is not bounded UTF-8 JSON") from error
    if not isinstance(payload, list) or len(payload) > MAX_TOPICS:
        raise ValueError("canonical corpus must be an array of at most 10,000 topics")
    topics = tuple(Topic.model_validate(record) for record in payload)
    keys = [(topic.source_id, topic.topic_id) for topic in topics]
    if len(set(keys)) != len(keys):
        raise ValueError("duplicate source/topic identity in canonical corpus")
    return topics


def _semantic(topic: Topic) -> dict[str, Any]:
    """Separate meaningful content from revision labels and extraction coordinates."""
    return {
        "title": topic.title,
        "content_type": topic.content_type.value,
        "blocks": [
            block.model_dump(mode="json", exclude={"provenance", "source_block_id"})
            for block in topic.blocks
        ],
    }


def _notices(topic: Topic | None) -> list[dict[str, Any]]:
    """Retain full cited safety records so removal, relocation and changed advice remain visible."""
    return (
        []
        if topic is None
        else [block.model_dump(mode="json") for block in topic.blocks if block.warning is not None]
    )


def _digest(topics: tuple[Topic, ...]) -> str:
    """Fingerprint the validated sorted corpus rather than irrelevant JSON whitespace."""
    content = json.dumps(
        [
            topic.model_dump(mode="json")
            for topic in sorted(topics, key=lambda t: (t.source_id, t.topic_id))
        ],
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(content).hexdigest()


def compare_topics(before: tuple[Topic, ...], after: tuple[Topic, ...]) -> dict[str, Any]:
    """Compare source/topic identities in O(n log n + b) time and O(b) report space.

    Args:
        before: Validated baseline corpus. Duplicate identities are rejected by load_topics.
        after: Candidate corpus; matching does not rely on title or list order.
    Returns:
        Deterministic changes with full cited before/after records and explicit review flags.
    """
    old = {(topic.source_id, topic.topic_id): topic for topic in before}
    new = {(topic.source_id, topic.topic_id): topic for topic in after}
    if len(old) != len(before) or len(new) != len(after):
        raise ValueError("duplicate source/topic identity in canonical corpus")
    counts = dict.fromkeys(("added", "removed", "changed", "unchanged"), 0)
    changes = []
    for key in sorted(old.keys() | new.keys()):
        previous, current = old.get(key), new.get(key)
        status = (
            "added"
            if previous is None
            else "removed"
            if current is None
            else ("unchanged" if previous == current else "changed")
        )
        counts[status] += 1
        if status == "unchanged":
            continue
        fields = []
        if previous is not None and current is not None:
            if _semantic(previous) != _semantic(current):
                fields.append("content")
            if previous.source_revision != current.source_revision:
                fields.append("source_revision")
            if [(b.source_block_id, b.provenance) for b in previous.blocks] != [
                (b.source_block_id, b.provenance) for b in current.blocks
            ]:
                fields.append("provenance")
        else:
            fields.append("topic_presence")
        present = current if current is not None else previous
        assert present is not None
        changes.append(
            {
                "source_id": key[0],
                "topic_id": key[1],
                "title": present.title,
                "status": status,
                "changed_fields": fields,
                "safety_review_required": _notices(previous) != _notices(current),
                "before": None if previous is None else previous.model_dump(mode="json"),
                "after": None if current is None else current.model_dump(mode="json"),
            }
        )
    return {
        "comparison_version": 1,
        "before_sha256": _digest(before),
        "after_sha256": _digest(after),
        "counts": counts,
        "changes": changes,
    }


def write_comparison(before: Path, after: Path, output: Path) -> dict[str, Any]:
    """Validate both corpora, then exclusively create a separate JSON/HTML review directory.

    Args:
        before: Baseline canonical file; never changed.
        after: Candidate canonical file; never changed.
        output: Fresh directory with an existing parent; existing paths are never overwritten.
    Returns:
        The comparison dossier. An operational write failure may leave partial reports for review.
    """
    report = compare_topics(load_topics(before), load_topics(after))
    encoded = json.dumps(report, indent=2, sort_keys=True, allow_nan=False) + "\n"
    environment = Environment(autoescape=select_autoescape(default=True), undefined=StrictUndefined)
    html = environment.from_string(HTML_TEMPLATE).render(report=report) + "\n"
    output.mkdir()
    (output / "comparison.json").write_text(encoded, encoding="utf-8", newline="\n")
    (output / "comparison.html").write_text(html, encoding="utf-8", newline="\n")
    return report
